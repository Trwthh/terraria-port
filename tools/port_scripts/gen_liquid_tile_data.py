"""Generates port/crates/terraria-sim/src/liquid_tile_data.rs from refdata/tile_object_data.json.

The table is what `TileObjectData.CheckWaterDeath(Tile)` / `CheckLavaDeath(Tile)` (TileObjectData.cs:5084, 5108) need from
`TileObjectData.GetTileData(Tile)` (TileObjectData.cs:5197): per tile type the style arithmetic fields, and for the base and for
every sub-tile (style) its `WaterDeath`, `LavaDeath`, `UsesGlobalLiquidChecks` and its alternates (`Style`, `RandomStyleRange`).
`refdata/tile_object_data.json` is written by tools/refdump (the game's own TileObjectData after Initialize()); in its
`styles` list, entry i is `GetTileData(type, i)`, i.e. `SubTiles[i]` or the base where the slot is null.

Run:  python -I tools/port_scripts/gen_liquid_tile_data.py
"""
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "refdata", "tile_object_data.json")
DST = os.path.join(ROOT, "port", "crates", "terraria-sim", "src", "liquid_tile_data.rs")

# the three tile types whose TileObjectData has a GetStyleOverride delegate (GetStyle_Stalactite, GetStyle_SmallPiles, GetStyle_Detritus)
STYLE_OVERRIDE = {165, 185, 233}


def bits(d):
    return (1 if d["WaterDeath"] else 0) | (2 if d["LavaDeath"] else 0) | (4 if d["UsesGlobalLiquidChecks"] else 0)


def alts(lst):
    return "&[" + ", ".join("a({}, {}, {})".format(a["data"]["Style"], a["data"]["RandomStyleRange"], bits(a["data"])) for a in lst) + "]"


def main():
    d = json.load(open(SRC))
    out = []
    out.append("//! GENERATED by tools/port_scripts/gen_liquid_tile_data.py from refdata/tile_object_data.json. Do not edit.")
    out.append("//!")
    out.append("//! The part of `TileObjectData` that `TileObjectData.CheckWaterDeath(Tile)` and `CheckLavaDeath(Tile)` read")
    out.append("//! (TileObjectData.cs:5084, 5108), see `liquid::tile_object_data_get_tile_data`.")
    out.append("")
    out.append("/// `WaterDeath` = 1, `LavaDeath` = 2, `UsesGlobalLiquidChecks` = 4")
    out.append("pub type Liq = u8;")
    out.append("/// An alternate of a `TileObjectData`: its `Style`, `RandomStyleRange` and flags.")
    out.append("pub struct Alt {")
    out.append("    pub style: i32,")
    out.append("    pub random_style_range: i32,")
    out.append("    pub liq: Liq,")
    out.append("}")
    out.append("/// `TileObjectData.GetTileData(type, style)` for one style: the flags of the data that applies and its alternates.")
    out.append("pub struct StyleEntry {")
    out.append("    pub liq: Liq,")
    out.append("    pub alternates: &'static [Alt],")
    out.append("}")
    out.append("/// One tile type's `TileObjectData` (`_data[type]`).")
    out.append("pub struct ObjectData {")
    out.append("    pub type_: u16,")
    out.append("    pub coordinate_full_width: i32,")
    out.append("    pub coordinate_full_height: i32,")
    out.append("    pub style_wrap_limit: i32,")
    out.append("    pub style_horizontal: bool,")
    out.append("    pub style_multiplier: i32,")
    out.append("    pub style_line_skip: i32,")
    out.append("    /// `GetStyleOverride != null`")
    out.append("    pub has_style_override: bool,")
    out.append("    pub base: Liq,")
    out.append("    pub base_alternates: &'static [Alt],")
    out.append("    /// `SubTiles` (`styles[i]` is `SubTiles[i]`, or the base data where that slot is null); empty when `SubTiles == null`")
    out.append("    pub styles: &'static [StyleEntry],")
    out.append("}")
    out.append("const fn a(style: i32, random_style_range: i32, liq: Liq) -> Alt {")
    out.append("    Alt { style, random_style_range, liq }")
    out.append("}")
    out.append("const fn s(liq: Liq, alternates: &'static [Alt]) -> StyleEntry {")
    out.append("    StyleEntry { liq, alternates }")
    out.append("}")
    out.append("")
    out.append("pub static OBJECT_DATA: &[ObjectData] = &[")
    for t in sorted(d["tileObjectData"], key=lambda e: e["tile"]):
        b = t["base"]
        has_override = t["tile"] in STYLE_OVERRIDE
        if has_override:
            assert b.get("GetStyleOverride"), t["tile"]
        else:
            assert not b.get("GetStyleOverride"), t["tile"]
        out.append("    ObjectData {{ type_: {}, coordinate_full_width: {}, coordinate_full_height: {}, style_wrap_limit: {}, style_horizontal: {}, style_multiplier: {}, style_line_skip: {}, has_style_override: {}, base: {}, base_alternates: {}, styles: &[{}] }},".format(
            t["tile"], b["CoordinateFullWidth"], b["CoordinateFullHeight"], b["StyleWrapLimit"], str(b["StyleHorizontal"]).lower(),
            b["StyleMultiplier"], b["StyleLineSkip"], str(has_override).lower(), bits(b), alts(t["alternates"]),
            ", ".join("s({}, {})".format(bits(s["data"]), alts(s["alternates"])) for s in t["styles"])))
    out.append("];")
    out.append("")
    with open(DST, "w", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote", DST, len(d["tileObjectData"]), "tile types")


main()
