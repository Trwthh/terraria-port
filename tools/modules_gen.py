#!/usr/bin/env python3
"""Write tools/modules.txt (gamedb module rules) from the namespaces the decompile actually declares.

One module per namespace two levels deep (`Terraria.Audio`), three levels inside the big buckets
(`Terraria.GameContent.*`, `Terraria.Graphics.*`, `ReLogic.Peripherals.*`), plus one module for each of
the large root classes (Main, Player, NPC, ...). Deterministic: same decompile -> same file.
"""
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEEP = ("Terraria.GameContent", "Terraria.Graphics", "ReLogic.Peripherals")
ROOT_FILE_MIN_LINES = 3000      # a root-namespace file this large is a subsystem of its own

ns_files = {}
for line in open(ROOT / "meta" / "src" / "src_decls.jsonl", encoding="utf-8"):
    path, kind, container = json.loads(line)[:3]
    if kind in ("class", "struct", "interface", "enum", "delegate") and path not in ns_files:
        ns_files[path] = container            # first declared type; top-level types come first in ILSpy output


def bucket(ns):
    parts = ns.split(".")
    depth = 3 if any(ns == d or ns.startswith(d + ".") for d in DEEP) else 2
    return ".".join(parts[:depth])


system = lambda ns: "ReLogic" if ns.startswith("ReLogic") else "Terraria"
rules, seen = [], set()
for path, ns in sorted(ns_files.items()):
    if ns in ("Terraria", "ReLogic"):
        continue
    b = bucket(ns)
    if b not in seen and "." in b:
        seen.add(b)
        rules.append((f"n:{b}", b.lower(), system(b)))
for root_ns in ("Terraria", "ReLogic"):
    rules.append((f"x:{root_ns}", root_ns.lower() + ".core", system(root_ns)))
for path, ns in sorted(ns_files.items()):
    if ns == "Terraria" and sum(1 for _ in open(ROOT / "decompile" / path, "rb")) >= ROOT_FILE_MIN_LINES:
        name = path.rsplit("/", 1)[1]
        rules.append((f"b:{name}", "terraria.core." + name[:-3].lower(), "Terraria"))
other = sorted({ns.split(".")[0] for ns in ns_files.values()} - {"Terraria", "ReLogic"})
for top in other:                              # BCrypt.Net, Properties, global namespace helpers
    if top:
        rules.append((f"n:{top}", "thirdparty." + top.lower(), "ThirdParty", "@depth=1"))

rules.append(("b:AssemblyInfo.cs", "meta.assemblyinfo", "ThirdParty"))

out = ["# generated by tools/modules_gen.py - edit the generator, not this file",
       "# selector\tmodule_id\tsystem"]
out += ["\t".join(r) for r in rules]
(ROOT / "tools" / "modules.txt").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print(f"modules_gen: {len(rules)} rules")
