#!/usr/bin/env python3
"""Generate port/crates/terraria-data/src/{ids,main_arrays,sets}.rs from refdata/*.json.

refdata/ is written by tools/refdump (the game's own code, run headless). Naming follows the port-wide
rule in port/PORTING.md: modules and fields are snake_case of the C# name, statics and constants
SCREAMING_SNAKE_CASE of it (`TileID.Sets.ForcedDirtMerging` -> `tile_id::sets::FORCED_DIRT_MERGING`,
`Main.tileSolid` -> `MainArrays::tile_solid`). Deterministic: same refdata -> same files.
"""
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REF = ROOT / "refdata"
OUT = ROOT / "port" / "crates" / "terraria-data" / "src"
NL = "\n"
HEADER = "// @generated by tools/gen_tables.py from refdata/{} - do not edit" + NL + "#![allow(clippy::all)]" + NL + NL
RUST_KEYWORDS = {"as", "break", "const", "continue", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move",
                 "mut", "pub", "ref", "return", "static", "struct", "trait", "true", "type", "unsafe", "use", "where", "while", "async",
                 "await", "dyn", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen"}
RAW_FORBIDDEN = {"self", "Self", "super", "crate"}
# Main.* arrays that are animation state, not data
RUNTIME_STATE = {"tileFrame", "tileFrameCounter", "wallFrame", "wallFrameCounter"}


def snake(name):
    """The port-wide C# -> Rust name rule (also documented in port/PORTING.md)."""
    s = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    s = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", "_", s)
    return s.lower()


def ident(name):
    name = re.sub(r"[^A-Za-z0-9_]", "_", name)
    if name[0].isdigit():
        name = "_" + name
    if name in RAW_FORBIDDEN or name in RUST_KEYWORDS:
        return name + "_"
    return name


def screaming(name):
    return ident(snake(name).upper())


def check_unique(names, where):
    seen = {}
    for n in names:
        k = screaming(n)
        if k in seen and seen[k] != n:
            raise SystemExit(f"name collision in {where}: {seen[k]} and {n} both become {k}")
        seen[k] = n


def elem_type(values):
    """Rust element type for a flat JSON array, or None when it is not a plain numeric / bool array."""
    if not values:
        return None
    if all(isinstance(v, bool) for v in values):
        return "bool"
    if all(isinstance(v, int) and not isinstance(v, bool) for v in values):
        lo, hi = min(values), max(values)
        return "i32" if -2**31 <= lo and hi < 2**31 else "i64" if lo < 0 else "u32" if hi < 2**32 else "u64"
    if all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in values):
        return "f32"
    return None


def lit(v, ty):
    if ty == "bool":
        return "true" if v else "false"
    if ty == "f32":
        f = float(v)
        if f != f:
            return "f32::NAN"
        if f in (float("inf"), float("-inf")):
            return "f32::INFINITY" if f > 0 else "f32::NEG_INFINITY"
        r = repr(f)
        return r if ("." in r or "e" in r) else r + ".0"
    return str(v)


def array(name, values, ty):
    body = ", ".join(lit(v, ty) for v in values)
    return f"pub static {screaming(name)}: [{ty}; {len(values)}] = [{body}];" + NL


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    report = []

    # ---- ids.rs
    ids = json.loads((REF / "id_constants.json").read_text(encoding="utf-8"))
    ids = ids.get("classes", ids)
    out = [HEADER.format("id_constants.json")]
    n = 0
    for cls in sorted(ids):
        consts = ids[cls]
        if not isinstance(consts, dict):
            continue
        numeric = {k: v for k, v in consts.items() if isinstance(v, (int, float)) and not isinstance(v, bool)}
        check_unique(numeric, cls)
        out.append(f"/// `Terraria.ID.{cls}`" + NL + f"pub mod {snake(cls.replace('.', '_'))} {{" + NL)
        for k in sorted(numeric, key=lambda k: (numeric[k], k)):
            v = numeric[k]
            ty = "f32" if isinstance(v, float) else ("i32" if -2**31 <= v < 2**31 else "i64")
            out.append(f"    /// `{cls}.{k}`" + NL + f"    pub const {screaming(k)}: {ty} = {lit(v, ty)};" + NL)
            n += 1
        out.append("}" + NL + NL)
    (OUT / "ids.rs").write_text("".join(out), encoding="utf-8", newline="\n")
    report.append(f"ids.rs: {n} constants in {len(ids)} classes")

    # ---- main_arrays.rs
    t = json.loads((REF / "tile_arrays.json").read_text(encoding="utf-8"))
    out = [HEADER.format("tile_arrays.json"),
           "//! Initial contents of the `Main.tileXxx` / `Main.wallXxx` arrays after `Main.Initialize()`." + NL,
           "//! The game changes some of these while running, so the simulation holds a mutable copy (`MainArrays`)." + NL + NL,
           f"pub const TILE_COUNT: usize = {t['tileCount']};" + NL + f"pub const WALL_COUNT: usize = {t['wallCount']};" + NL + NL]
    fields = []
    for group in ("tile", "wall"):
        for name in sorted(t[group]):
            if name in RUNTIME_STATE:
                continue
            ty = elem_type(t[group][name])
            if ty is None:
                report.append(f"main_arrays.rs: skipped Main.{name} (not a plain array)")
                continue
            out.append(f"/// `Main.{name}`" + NL + array(name, t[group][name], ty))
            fields.append((name, ty))
    check_unique([f for f, _ in fields], "Main arrays")
    pairs = ", ".join(f"({a}, {b})" for a, b in t["tileMerge"])
    out.append("/// `Main.tileMerge[a][b] == true` pairs" + NL + f"pub static TILE_MERGE: [(usize, usize); {len(t['tileMerge'])}] = [{pairs}];" + NL + NL)
    out.append("/// Mutable copies of every table above, as the running game holds them." + NL + "#[derive(Clone, Debug)]" + NL + "pub struct MainArrays {" + NL)
    for name, ty in fields:
        out.append(f"    /// `Main.{name}`" + NL + f"    pub {ident(snake(name))}: Vec<{ty}>," + NL)
    out.append("    /// `Main.tileMerge[a][b]`" + NL + "    pub tile_merge: Vec<Vec<bool>>," + NL + "}" + NL + NL)
    out.append("impl Default for MainArrays {" + NL + "    fn default() -> Self {" + NL
               + "        let mut tile_merge = vec![vec![false; TILE_COUNT]; TILE_COUNT];" + NL
               + "        for &(a, b) in TILE_MERGE.iter() {" + NL + "            tile_merge[a][b] = true;" + NL + "        }" + NL + "        Self {" + NL)
    for name, ty in fields:
        out.append(f"            {ident(snake(name))}: {screaming(name)}.to_vec()," + NL)
    out.append("            tile_merge," + NL + "        }" + NL + "    }" + NL + "}" + NL)
    (OUT / "main_arrays.rs").write_text("".join(out), encoding="utf-8", newline="\n")
    report.append(f"main_arrays.rs: {len(fields)} arrays")

    # ---- sets.rs
    s = json.loads((REF / "id_sets.json").read_text(encoding="utf-8"))
    s = s.get("sets", s)
    tree = {}
    skipped = []
    for key in sorted(s):
        v = s[key]
        if isinstance(v, dict) and set(v) == {"_arr"}:      # ImmunityCooldownID.Sets.*: wrapper around one array
            v = v["_arr"]
        ty = elem_type(v) if isinstance(v, list) else None
        if ty is None:
            skipped.append(key)
            continue
        parts = key.split(".")
        node = tree
        for p in parts[:-1]:
            node = node.setdefault(snake(p), {})
        node[parts[-1]] = (key, v, ty)
    out = [HEADER.format("id_sets.json"), "//! The `Terraria.ID.*.Sets` tables after `PostSetupContent`." + NL + NL]
    count = [0]

    def emit(node, depth):
        pad = "    " * depth
        check_unique([k for k, v in node.items() if not isinstance(v, dict)], "a Sets class")
        for k in sorted(node):
            v = node[k]
            if isinstance(v, dict):
                out.append(f"{pad}pub mod {ident(k)} {{" + NL)
                emit(v, depth + 1)
                out.append(f"{pad}}}" + NL)
            else:
                key, values, ty = v
                out.append(f"{pad}/// `{key}`" + NL + pad + array(k, values, ty))
                count[0] += 1
    emit(tree, 0)
    (OUT / "sets.rs").write_text("".join(out), encoding="utf-8", newline="\n")
    report.append(f"sets.rs: {count[0]} arrays, {len(skipped)} not plain arrays (kept only in refdata/id_sets.json): {', '.join(skipped)}")

    (OUT / "lib.rs").write_text("//! Game data tables generated from the running game (tools/refdump -> refdata/ -> tools/gen_tables.py)." + NL
                                + "pub mod ids;" + NL + "pub mod main_arrays;" + NL + "pub mod sets;" + NL + "pub use main_arrays::MainArrays;" + NL, encoding="utf-8", newline="\n")
    (ROOT / "port" / "crates" / "terraria-data" / "GENERATED.md").write_text(NL.join(report) + NL, encoding="utf-8", newline="\n")
    print(NL.join(r[:300] for r in report))


if __name__ == "__main__":
    main()
