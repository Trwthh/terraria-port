#!/usr/bin/env python3
"""Writes port/crates/terraria-gen-game/tests/client/steps.rs: the top-level statements of the generated functions
on the CLIENT start-up path, each wrapped in `st!( .. )`, so tests/client.rs can run every statement caught on its
own (the survey technique of tests/survey.rs, but derived from the generated code instead of copied by hand).

DIAGNOSTIC ONLY. The proof of the client start-up is the single call sequence in tests/client.rs (`CLIENT_WHOLE=1`).

A function is expanded in place when a statement is exactly a call of it with the arguments `(this)` or `()`.
Typed `let` statements are hoisted (`let mut x: T = rt::zero(); st!(x = expr);`) so later statements still see them.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
GEN = os.path.join(HERE, "..", "..", "port", "crates", "terraria-gen-game", "src", "gen")
OUT = os.path.join(HERE, "..", "..", "port", "crates", "terraria-gen-game", "tests", "client", "steps.rs")

# rust path of the function -> expanded in place where it is called as a statement with (this) / ()
EXPAND = [
    "terraria::main::initialize",
    "terraria::main::client_initialize",
    "terraria::main::load_content",
    "terraria::main::load_content_shaders",
    "terraria::main::load_content_try_entering_hi_def",
    "terraria::main::load_settings",
    "terraria::main::post_content_load_initialize",
    "terraria::initializers::asset_initializer::load_splash_assets",
    "terraria::initializers::chroma_initializer::load",
    "terraria::initializers::ui_links_initializer::load",
]
# calls that stand for a virtual call into translated code: base.Initialize() runs Main.LoadContent()
ALIAS = {"terraria_host::game::base_initialize": "terraria::main::load_content"}
# name of the generated statement list -> root function
ROOTS = [
    ("initialize", "terraria::main::initialize"),
    # what DrawSplash runs when the splash ends (Main.cs:53456-53457)
    ("initialize_almost_everything", "terraria::main::initialize_almost_everything"),
    ("post_content_load_initialize", "terraria::main::post_content_load_initialize"),
]

_cache = {}


def body_of(path):
    """Top-level statement lines of the generated function `path` (a::b::fn)."""
    if path in _cache:
        return _cache[path]
    parts = path.split("::")
    f = os.path.join(GEN, *parts[:-1]) + ".rs"
    src = open(f, encoding="utf-8").read().split("\n")
    pat = re.compile(r"^pub unsafe fn " + re.escape(parts[-1]) + r"\(")
    start = next((i for i, l in enumerate(src) if pat.match(l)), None)
    if start is None:
        raise SystemExit(f"{path}: not found in {f}")
    end = next(i for i in range(start + 1, len(src)) if src[i] == "}")
    _cache[path] = src[start + 1:end]
    return _cache[path]


def statements(lines):
    """Groups lines into top-level statements (indent 4)."""
    out, cur = [], []
    header = False  # the previous top-level line opens something that continues on the next one
    for l in lines:
        if not l.strip():
            continue
        top = l.startswith("    ") and not l.startswith("     ")
        t = l.strip()
        if top:
            cont = cur and (t.startswith("}") or t.startswith("else") or (t == "{" and header))
            if not cont and cur:
                out.append(cur)
                cur = []
            header = t.startswith("if ") or t.startswith("else") or t.endswith("loop") or t.endswith(":") or t == "}" and False
        cur.append(l)
    if cur:
        out.append(cur)
    return out


LET = re.compile(r"^    let mut (\w+): (.+?) = (.*);$", re.S)
CALL = re.compile(r"^    ((?:\w+::)+\w+)\((this)?\);$")


def emit(path, out, depth=0, seen=()):
    for st in statements(body_of(path)):
        text = "\n".join(st).replace("crate::", "terraria_gen_game::")
        if len(st) == 1:
            m = CALL.match(st[0])
            target = ALIAS.get(m.group(1), m.group(1)) if m else None
            if m and target in EXPAND and target not in seen:
                # its own scope: the hoisted locals of two functions must not shadow each other
                out.append(f"    eprintln!(\"---- {target}\");")
                out.append("    {")
                emit(target, out, depth + 1, seen + (path,))
                out.append("    }")
                out.append(f"    eprintln!(\"---- end {target}\");")
                continue
        m = LET.match(text)
        if m:
            out.append(f"    let mut {m.group(1)}: {m.group(2)} = rt::zero();")
            out.append(f"    st!({m.group(1)} = {m.group(3)});")
            continue
        if text.strip() in ("return;",):
            continue
        out.append("    st!(" + text.strip() + ");")


def main():
    out = [
        "// @generated by tools/cs2rs/mk_client_survey.py from the generated code. Do not edit.",
        "// DIAGNOSTIC ONLY: every top-level statement of the client start-up functions, caught on its own.",
        "",
    ]
    for name, root in ROOTS:
        out.append("#[allow(unused_mut, unused_variables, unused_assignments, unused_unsafe, unused_parens, unused_braces, non_snake_case, unreachable_code)]")
        out.append(f"pub unsafe fn {name}(this: *mut terraria::main::Main) {{")
        emit(root, out)
        out.append("}")
        out.append("")
    text = "\n".join(out)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    if old != text:
        open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    print(f"client survey: {text.count('st!(')} statements ({'changed' if old != text else 'unchanged'})")


if __name__ == "__main__":
    sys.exit(main())
