                    }
                }
                mrows.Append($"    rt::MethodMeta {{ name: {Q(m.Name)}, public: {(m.DeclaredAccessibility == Accessibility.Public ? "true" : "false")}, is_static: {(m.IsStatic ? "true" : "false")}, attrs: {mattr}, bind: {bind} }},\n");
                mk++;
            }
            sb.Append($"static __{low.ToUpperInvariant()}_METHODS: [rt::MethodMeta; {mk}] = [\n{mrows}];\n");
            methodsRef = $"Some(&__{low.ToUpperInvariant()}_METHODS)";
        }
        string attrFn = "None";
        if (attrs.Count > 0)
        {
            sb.Append($"unsafe fn __{low}_attrs() -> Vec<Obj> {{\n    vec![\n{string.Concat(attrs.Select(x => "        " + x + ",\n"))}    ]\n}}\n");
            attrFn = $"Some(__{low}_attrs)";
        }
        // the base class's data (instance members are declared per level, as in the CLR)
        string baseRef = "None";
        var bt = M.Pop(t).Base;
        if ((members || M.ReflectMethods(t)) && bt != null && bt.WholeTypeReason == null && (members || M.ReflectMethods(bt)))
        {
            new Emitter(M, bt).TypeOfExpr(bt.Sym);
            baseRef = $"Some(&{Emitter.MetaIdent(Model.FullName(bt.Sym))})";
        }
        bool inst = t.Sym.GetMembers().OfType<IFieldSymbol>().Any(f => !f.IsStatic);
        string classId = t.TypeId != 0 ? $"{t.ModPath}::TYPE_ID" : "0";
        sb.Append($"/// `{name}`\npub static {ident}: rt::TypeMeta = rt::TypeMeta {{ name: {Q(name)}, clr_name: {Q(ClrName(t.Sym))}, flags: {flags}, tid: {tid}, class_id: {classId}, instance_fields: {(inst ? "true" : "false")}, members: {(members ? "true" : "false")}, attrs: {attrFn}, base: {baseRef}, methods: {methodsRef}, fields: &[\n{rows}], props: &[\n{prows}]}};\n\n");
        // a native struct without a box id (`Trace::BOX`): boxing it through reflection fails when it happens (a
        // run-time panic), not when the crate is built: most fields are never read this way
        sb.Replace("const { rt::box_id::<", "{ rt::box_id::<");
        return sb.ToString();
    }

    /// CLR-style name of a type for the default `ToString()` (`Terraria.Ref`1[System.Int32]`).
    public static string ClrName(ITypeSymbol t)
    {
        if (t is IArrayTypeSymbol a) return ClrName(a.ElementType) + "[" + new string(',', a.Rank - 1) + "]";
        if (t is not INamedTypeSymbol n) return t.Name;
        var parts = new List<string>();
        var args = new List<ITypeSymbol>();
        for (var c = n; c != null; c = c.ContainingType) { parts.Insert(0, c.MetadataName); args.InsertRange(0, c.TypeArguments); }
        var ns = n.ContainingNamespace == null || n.ContainingNamespace.IsGlobalNamespace ? "" : n.ContainingNamespace.ToDisplayString() + ".";
        return ns + string.Join("+", parts) + (args.Count == 0 ? "" : "[" + string.Join(",", args.Select(ClrName)) + "]");
    }

    /// The virtuals of `System.Object` for objects of this type (`rt::Trace::obj_equals` ...), reached through the
    /// object header from any handle: DESIGN.md section 2.
    string ObjectVirtuals(TType t)
    {
        var sb = new StringBuilder();
        string eq = ObjectOverrideCall(t, "Equals", 1, "this", "other");
        string hash = ObjectOverrideCall(t, "GetHashCode", 0, "this", null);
        string str = ObjectOverrideCall(t, "ToString", 0, "this", null);
        if (t.IsStruct)
        {
            // a boxed struct: ValueType.Equals compares field by field when the struct does not override it
            sb.Append($"    unsafe fn obj_equals(this: *const Self, other: Obj) -> bool {{\n        {(eq ?? "rt::is_boxed(other, TYPE_ID) && __fieldwise_eq(&*this, &*(other.0 as *const Self))")}\n    }}\n");
            sb.Append($"    unsafe fn obj_hash(this: *const Self) -> i32 {{\n        {(hash ?? "__fieldwise_hash(&*this)")}\n    }}\n");
        }
        else
        {
            if (eq != null) sb.Append($"    unsafe fn obj_equals(this: *const Self, other: Obj) -> bool {{\n        {eq}\n    }}\n");
            if (hash != null) sb.Append($"    unsafe fn obj_hash(this: *const Self) -> i32 {{\n        {hash}\n    }}\n");
            var ke = EquatableCall(t, "a.0", "b");
            if (ke != null) sb.Append($"    unsafe fn key_eq(a: Gc<Self>, b: Gc<Self>) -> bool {{\n        {ke}\n    }}\n");
        }
        bool isExc = false;
        for (var c = t; c != null; c = c.Base) if (c.ExcKind != null) isExc = true;
        if (str != null) sb.Append($"    unsafe fn obj_to_string(this: *const Self) -> Str {{\n        {str}\n    }}\n");
        else if (isExc) sb.Append("    unsafe fn obj_to_string(this: *const Self) -> Str {\n        <rt::Exception as rt::Trace>::obj_to_string(this as *const rt::Exception)\n    }\n");
        else sb.Append($"    unsafe fn obj_to_string(_this: *const Self) -> Str {{\n        Str::lit({Q(ClrName(t.Sym))})\n    }}\n");
        return sb.ToString();
    }

    /// Equality of a struct as `EqualityComparer<S>.Default` computes it (dictionary keys, `List.Contains` ...):
    /// `IEquatable<S>.Equals(S)` when the struct implements the interface, else `Equals(object)` (the struct's
    /// override, or `ValueType.Equals`: field by field). `GetHashCode()`: the override, else a fold of the field
    /// hashes (deviation: `ValueType.GetHashCode` of the CLR is a different number; nothing but a direct call
    /// can observe it, enumeration order of `Dictionary` / `HashSet` does not depend on hashes).
    void EmitKey(StringBuilder o, TType t)
    {
        var fields = t.InstFields.Where(f => f.RustType != null).ToList();
        o.Append($"/// `ValueType.Equals` / `ValueType.GetHashCode`: field by field.\nfn __fieldwise_eq(a: &{t.StructName}, b: &{t.StructName}) -> bool {{\n    ");
        o.Append(fields.Count == 0 ? "let _ = (a, b);\n    true" : string.Join(" && ", fields.Select(f => $"rt::CsKey::cs_eq(&a.{f.Name}, &b.{f.Name})")));
        o.Append($"\n}}\nfn __fieldwise_hash(a: &{t.StructName}) -> i32 {{\n    let mut h: i32 = 0;\n");
        foreach (var f in fields) o.Append($"    h = h.wrapping_mul(31).wrapping_add(rt::CsKey::cs_hash_code(&a.{f.Name}));\n");
        o.Append("    let _ = a;\n    h\n}\n");
        string self = "self as *const Self as *mut Self";
        string eq = EquatableCall(t, "(" + self + ")", "*o") ?? ObjectOverrideCall(t, "Equals", 1, "(" + self + ")", "rt::box_value(*o, TYPE_ID)");
        string hash = ObjectOverrideCall(t, "GetHashCode", 0, "(" + self + ")", null);
        o.Append($"impl rt::CsKey for {t.StructName} {{\n    fn cs_eq(&self, o: &Self) -> bool {{\n");
        o.Append(eq != null ? $"        unsafe {{ {eq} }}\n" : "        __fieldwise_eq(self, o)\n");
        o.Append("    }\n    fn cs_hash<H: core::hash::Hasher>(&self, h: &mut H) {\n        h.write_i32(rt::CsKey::cs_hash_code(self));\n    }\n    fn cs_hash_code(&self) -> i32 {\n");
        if (hash != null) o.Append($"        unsafe {{ {hash} }}\n");
        else if (eq != null) o.Append("        // user-defined equality without GetHashCode: every value hashes alike (consistent with any Equals)\n        0\n");
        else o.Append("        __fieldwise_hash(self)\n");
        o.Append("    }\n}\n");
        // `Comparer<S>.Default` (OrderBy / Sort keys): the struct's IComparable<S>.CompareTo(S), else IComparable.CompareTo(object)
        foreach (var i in t.Sym.AllInterfaces)
        {
            bool generic = i.OriginalDefinition.ToDisplayString() == "System.IComparable<T>" && SymbolEqualityComparer.Default.Equals(i.TypeArguments[0], t.Sym);
            bool plain = i.ToDisplayString() == "System.IComparable" && !t.Sym.AllInterfaces.Any(x => x.OriginalDefinition.ToDisplayString() == "System.IComparable<T>" && SymbolEqualityComparer.Default.Equals(x.TypeArguments[0], t.Sym));
            if (!generic && !plain) continue;
            var im = i.GetMembers("CompareTo").OfType<IMethodSymbol>().FirstOrDefault();
            if (im == null || t.Sym.FindImplementationForInterfaceMember(im) is not IMethodSymbol impl) continue;
            var it = M.Get(impl.ContainingType); var mi = it == null ? null : M.Method(it, impl);
            if (mi == null || !mi.Emittable) continue;
            o.Append($"impl rt::sys::CsOrd for {t.StructName} {{\n    fn cs_cmp(&self, o: &Self) -> i32 {{\n        unsafe {{ {it.ModPath}::{mi.Name}({self}, {(generic ? "*o" : "rt::box_value(*o, TYPE_ID)")}) }}\n    }}\n}}\n");
            break;
        }
    }

    /// The override of `impl` that objects of class `x` run: `impl` itself unless it is virtual / abstract and `x` or
    /// a class between `x` and its declaring class overrides it.
    public static IMethodSymbol MostDerived(INamedTypeSymbol x, IMethodSymbol impl)
    {
        if (impl == null || !(impl.IsAbstract || impl.IsVirtual || impl.IsOverride)) return impl;
        for (var c = x; c != null && !SymbolEqualityComparer.Default.Equals(c, impl.ContainingType); c = c.BaseType)
            foreach (var cm in c.GetMembers(impl.Name).OfType<IMethodSymbol>())
                for (var ov = cm.OverriddenMethod; ov != null; ov = ov.OverriddenMethod)
                    if (SymbolEqualityComparer.Default.Equals(ov.OriginalDefinition, impl.OriginalDefinition)) return cm;
        return impl;
    }

    /// `iface::m__v(this, args)`: selects the implementation by the type id of the object (class, or boxed struct).
    void EmitInterfaceDispatcher(TType t, MethodInfo2 mi, StringBuilder o)
    {
        var m = mi.Sym;
        if (!mi.Emittable || m.IsStatic) return;
        var sig = Sig(t, mi, mi.Name + "__v", out var ret, out var an);
        var arms = new SortedDictionary<string, List<string>>(StringComparer.Ordinal);
        foreach (var x in M.Ordered)
        {
            if (x.TypeId == 0 || x.Sym.IsAbstract || x.WholeTypeReason != null) continue;
            if (!x.Sym.AllInterfaces.Any(i => SymbolEqualityComparer.Default.Equals(i, t.Sym))) continue;
            var impl = x.Sym.FindImplementationForInterfaceMember(mi.Open ?? m) as IMethodSymbol;
            // Roslyn names the method of the class that lists the interface. When that method is virtual / abstract and
            // `x` (or a class between) overrides it, the object's own override is what an interface call runs.
            impl = MostDerived(x.Sym, impl);
            string call;
            var it = impl == null ? null : M.Get(impl.ContainingType);
            var imi = it == null ? null : M.MethodInst(it, impl, mi.TypeArgs);
            if (imi != null && imi.Emittable && !impl.IsAbstract)
                call = $"{it.ModPath}::{imi.Name}({string.Join(", ", new[] { $"this as *mut {it.StructPath}" }.Concat(an))})";
            else call = $"rt::unported::<{ret}>({Q(x.Sym.Name + "." + m.Name + " (interface implementation not translated)")})";
            if (!arms.TryGetValue(call, out var ids)) arms[call] = ids = new List<string>();
            ids.Add($"{x.ModPath}::TYPE_ID");
        }
        var dr = new MethodReport { Type = t, Sym = null, Display = Display(m) + " (interface dispatch)", Key = t.ModPath + "::" + mi.Name + "__v", Status = MStatus.Clean };
        foreach (var k in arms.Keys) { int p = k.IndexOf('('); if (p > 0 && !k.StartsWith("rt::")) dr.Calls.Add(k.Substring(0, p)); }
        Dispatchers.Add(dr);
        o.Append($"/// Interface dispatch of `{Display(m)}`.\n{sig} {{\n");
        o.Append("    match rt::type_id_of(this as *const u8) {\n");
        foreach (var kv in arms) o.Append($"        {string.Join(" | ", kv.Value)} => {kv.Key},\n");
        o.Append($"        _ => rt::unported::<{ret}>({Q(Display(m) + " (no translated implementation for this object)")}),\n    }}\n}}\n\n");
    }

    // ---- reflection (what tools\refdump reads)
    static bool IsSimpleOrXna(ITypeSymbol t)
    {
        if (t.TypeKind == TypeKind.Enum || t.SpecialType == SpecialType.System_String || t.SpecialType == SpecialType.System_Decimal) return true;
        if (Model.Prim(t.SpecialType) != null) return true;
        var n = Model.FullName(t);
        return n is "Microsoft.Xna.Framework.Color" or "Microsoft.Xna.Framework.Vector2" or "Microsoft.Xna.Framework.Rectangle" or "Microsoft.Xna.Framework.Point";
    }

    string ValueExpr(ITypeSymbol t, string e)
    {
        if (t.SpecialType == SpecialType.System_Boolean) return $"rt::Value::Bool({e})";
        if (t.SpecialType == SpecialType.System_Char) return $"rt::Value::Char({e})";
        if (t.SpecialType == SpecialType.System_Single) return $"rt::Value::F32({e})";
        if (t.SpecialType == SpecialType.System_Double) return $"rt::Value::F64({e})";
        if (t.SpecialType == SpecialType.System_String) return $"rt::Value::str({e})";
        if (Model.Prim(t.SpecialType) != null || t.TypeKind == TypeKind.Enum) return $"rt::Value::Int({e} as i128)";
        if (t.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T)
            return $"(if {e}.has_value {{ {ValueExpr(((INamedTypeSymbol)t).TypeArguments[0], e + ".value")} }} else {{ rt::Value::Null }})";
        switch (Model.FullName(t))
        {
            case "Microsoft.Xna.Framework.Color": return $"rt::Value::color({e})";
            case "Microsoft.Xna.Framework.Vector2": return $"rt::Value::vector2({e})";
            case "Microsoft.Xna.Framework.Rectangle": return $"rt::Value::rectangle({e})";
            case "Microsoft.Xna.Framework.Point": return $"rt::Value::point({e})";
        }
        if (t is IArrayTypeSymbol { Rank: 1 } at && M.RT(at.ElementType) != null)
            return $"(if {e}.is_null() {{ rt::Value::Null }} else {{ rt::Value::Arr({e}.as_slice().iter().map(|__x| {ValueExpr(at.ElementType, "(*__x)")}).collect()) }})";
        var tt = M.Get(t);
        if (tt != null && tt.Cfg != null && tt.Cfg.Reflect && tt.IsClass && tt.TypeId != 0)
            return $"(if {e}.is_null() {{ rt::Value::Null }} else {{ rt::Value::Obj({tt.ModPath}::reflect_fields({e}.0)) }})";
        if (tt != null && tt.Cfg != null && tt.Cfg.Reflect && tt.IsStruct && tt.WholeTypeReason == null)
            return $"{{ let mut __c = {e}; rt::Value::Obj({tt.ModPath}::reflect_fields(core::ptr::addr_of_mut!(__c))) }}";
        return $"rt::Value::Skip({Q(Model.Short(t))})";
    }

    void EmitReflect(TType t, StringBuilder o)
    {
        o.Append($"/// Public instance fields with their C# names, as `tools\\refdump` reads them by reflection.\npub unsafe fn reflect_fields(this: *mut {t.StructPath}) -> Vec<(&'static str, rt::Value)> {{\n    let mut v: Vec<(&'static str, rt::Value)> = Vec::new();\n");
        if (t.Base != null)
        {
            if (t.Base.Cfg != null && t.Base.Cfg.Reflect) o.Append($"    v.extend({t.Base.ModPath}::reflect_fields(this as *mut {t.Base.StructPath}));\n");
            else o.Append($"    v.push((\"<base>\", rt::Value::Skip({Q("base class " + t.Base.StructName + " has no reflect")})));\n");
        }
        foreach (var f in t.InstFields)
        {
            if (f.Sym == null || f.Sym.DeclaredAccessibility != Accessibility.Public || f.Sym.AssociatedSymbol != null) continue;
            if (f.RustType == null) { o.Append($"    v.push(({Q(f.Sym.Name)}, rt::Value::Skip({Q(Model.Short(f.Sym.Type))})));\n"); continue; }
            o.Append($"    v.push(({Q(f.Sym.Name)}, {ValueExpr(f.Sym.Type, $"(*this).{f.Name}")}));\n");
        }
        o.Append("    v\n}\n\n");
        var props = new List<(string name, string call, ITypeSymbol type)>();
        for (var c = t; c != null; c = c.Base)
            foreach (var p in c.Sym.GetMembers().OfType<IPropertySymbol>())
            {
                if (p.IsStatic || p.IsIndexer || p.DeclaredAccessibility != Accessibility.Public || p.GetMethod == null || p.GetMethod.DeclaredAccessibility != Accessibility.Public) continue;
                if (!IsSimpleOrXna(p.Type) || props.Any(x => x.name == p.Name)) continue;
                var mi = M.Method(c, p.GetMethod);
                if (mi == null || !mi.Emittable) { props.Add((p.Name, null, p.Type)); continue; }
                bool virt = p.GetMethod.IsVirtual || p.GetMethod.IsAbstract || p.GetMethod.IsOverride;
                // the dispatcher lives on the local root
                var root = p.GetMethod; var rt = c;
                while (virt && root.OverriddenMethod != null && M.Get(root.OverriddenMethod.ContainingType) is { } up && M.Method(up, root.OverriddenMethod) is { Emittable: true }) { root = root.OverriddenMethod; rt = up; }
                var rmi = M.Method(rt, root);
                props.Add((p.Name, $"{rt.ModPath}::{rmi.Name}{(virt ? "__v" : "")}(this as *mut {rt.StructPath})", p.Type));
            }
        props.Sort((a, b) => string.CompareOrdinal(a.name, b.name));
        o.Append($"/// Simple public properties (primitive / string / enum / Color / Vector2 / Rectangle / Point), by C# name.\npub const REFLECT_PROPS: &[&str] = &[{string.Join(", ", props.Select(p => Q(p.name)))}];\n");
        o.Append($"pub unsafe fn reflect_prop(this: *mut {t.StructPath}, index: usize) -> rt::Value {{\n    match index {{\n");
        for (int i = 0; i < props.Count; i++)
            o.Append(props[i].call == null ? $"        {i} => rt::Value::Skip(\"getter not emitted\"),\n" : $"        {i} => {ValueExpr(props[i].type, props[i].call)},\n");
        o.Append("        _ => rt::Value::Null,\n    }\n}\n\n");
    }
