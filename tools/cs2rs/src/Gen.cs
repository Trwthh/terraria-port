                    var em = new Emitter(M, tt);
                    read.Append($"        if let Some(v) = {C}::member::<{J}>(t, {Q(name)}) {{ {at}.{sefi.Name} = {C}::enum_from_token(v, &{em.EnumInfoRef(sen)}) as {sefi.RustType}; }}\n");
                    write.Append($"        {C}::set_member(j, {Q(name)}, {em.EnumToStringRef(sen, at + "." + sefi.Name)});\n");
                    continue;
                }
                if (jca != null) { var l = Loud($"member {m.Name} has a [JsonConverter] (not generated)"); read.Append($"        if {C}::has_member(t, {Q(name)}) {{ {l} }}\n"); write.Append($"        {l}\n"); continue; }
                if (r == null || !Convertible(mt)) { var l = Loud($"member {m.Name} of type {Model.Short(mt)} has no conversion in the generated member table"); read.Append($"        if {C}::has_member(t, {Q(name)}) {{ {l} }}\n"); write.Append($"        {l}\n"); continue; }
