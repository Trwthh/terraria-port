// Gen: one Rust module per translated C# type (struct, statics, constructors, methods, dispatchers, reflection).
using System.Collections.Concurrent;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Operations;

namespace Cs2Rs;

public sealed class MethodReport
{
    public TType Type; public IMethodSymbol Sym; public string Display; public MStatus Status;
    public List<(string kind, string where)> Fails = new();
    public List<string> Unported = new(); public List<string> Stubs = new(); public List<string> HostCalls = new();
    public List<string> Gaps = new(); public List<string> Calls = new();
    /// What the body reaches only in branches that `reachAssume` proves dead (subset of the lists above).
    public HashSet<string> DeadUnported = new(), DeadHostCalls = new(), DeadCalls = new();
    /// Rust path of the function (`mod::name`, `mod::cctor`, `mod::init_fields`).
    public string Key;
    public string NotEmittedReason; public int Lines;
}

public sealed class Gen
{
    readonly Model M;
    readonly ConcurrentDictionary<SyntaxTree, SemanticModel> _models = new();
    public readonly ConcurrentBag<MethodReport> Reports = new();
    /// Dispatcher functions: not bodies of the source, but nodes of the call graph (`--reach`).
    public readonly ConcurrentBag<MethodReport> Dispatchers = new();
    public Gen(Model m) { M = m; }

    /// Extra generated modules at the root of the gen tree (name, text).
    public IEnumerable<(string, string)> SupportModules(string genModule)
    {
        var head = $"use crate::rt;\nuse crate::rt::*;\nuse crate::s;\nuse crate::{genModule}::*;\n\n";
        // reflection data the config asks for even where no `typeof` mentions the type (before anything is written:
        // it may add enum tables)
        foreach (var rt in M.ReflectForced()) new Emitter(M, rt).TypeOfExpr(rt.Sym);
        // ... and the name tables of the enums the config's `reflect` selects
        foreach (var en in M.EnumIds.Keys.Where(e => M.ReflectsEnum(e)).OrderBy(Mono.Key, StringComparer.Ordinal)) new Emitter(M, M.Ordered[0]).TypeOfExpr(en);
        yield return ("ifaces", "// @generated by tools/cs2rs. Do not edit.\n//! Dispatchers for library interfaces that translated types implement.\n" + head + M.IfaceText());
        var metaTail = new StringBuilder("/// Every type with reflection data, by name.\npub static ALL: &[&rt::TypeMeta] = &[\n");
        foreach (var k in M.MetaFns.Keys.OrderBy(k => k, StringComparer.Ordinal)) metaTail.Append($"    &{Emitter.MetaIdent(k)},\n");
        // Activator.CreateInstance(type, nonPublic) of a type with reflection data (LeashedEntity.NewInstance creates an
        // object of its own runtime type): the parameterless constructor of every non-generic, non-abstract class with
        // data, with its accessibility
        var ctors = new StringBuilder();
        var ctorRows = new StringBuilder();
        foreach (var kv in M.MetaTypes.OrderBy(k => k.Key, StringComparer.Ordinal))
        {
            var ct = kv.Value;
            if (ct.IsStruct || ct.IsInterface || ct.WholeTypeReason != null || ct.Sym.TypeKind != TypeKind.Class || ct.Sym.IsAbstract || ct.Sym.IsStatic || ct.Sym.IsGenericType) continue;
            var c0 = ct.Sym.InstanceConstructors.FirstOrDefault(c => c.Parameters.Length == 0);
            if (c0 == null) continue;
            var cmi = M.Method(ct, c0.OriginalDefinition);
            if (cmi == null || !cmi.Emittable) continue;
            var fnName = "__ctor_" + Emitter.MetaIdent(kv.Key).ToLowerInvariant();
            ctors.Append($"unsafe fn {fnName}() -> Obj {{\n    {ct.ModPath}::new{cmi.Name.Substring(4)}().up::<Object>()\n}}\n");
            ctorRows.Append($"    ({Q(kv.Key)}, {(c0.DeclaredAccessibility == Accessibility.Public ? "true" : "false")}, {fnName}),\n");
        }
        metaTail.Append("];\n\n").Append(ctors).Append("/// Parameterless constructors of the classes with reflection data (`Activator.CreateInstance(type, nonPublic)`):\n/// type name, public, constructor.\npub static CTORS: &[(&str, bool, unsafe fn() -> Obj)] = &[\n").Append(ctorRows);
        metaTail.Append("];\n\n/// Makes every type's data known to the runtime (`o.GetType()` of an object, `Type.GetType(name)`,\n/// `Activator.CreateInstance`).\npub fn register_all() {\n    for m in ALL {\n        rt::meta_register(m);\n    }\n    for (name, public, ctor) in CTORS {\n        rt::ctor_register(name, *public, *ctor);\n    }\n}\n\n");
        metaTail.Append("/// Method-group delegates: method id (`Delegate::from_method`) -> `Declaring.Type+Nested.Method`.\npub static METHOD_NAMES: &[(u64, &str)] = &[\n");
        foreach (var kv in M.MethodNames.OrderBy(k => k.Key)) metaTail.Append($"    (0x{kv.Key:x}, {Q(kv.Value)}),\n");
        metaTail.Append("];\n");
        // Newtonsoft.Json over game classes (terraria-host REQUESTS.md 10): the member table of each class that flows
        // into the host's (de)serialiser, generated from the semantic model with Newtonsoft's default contract.
        // (a member of a game type pulls that type in, as Newtonsoft's contract resolver does: to a fixed point)
        var jsonDone = new Dictionary<INamedTypeSymbol, string>(SymbolEqualityComparer.Default);
        for (bool more = true; more;)
        {
            more = M.NoteDerivedJsonTypes();
            foreach (var jt in M.JsonTypes.Keys.OrderBy(Mono.Key, StringComparer.Ordinal).ToList())
                if (!jsonDone.ContainsKey(jt)) { jsonDone[jt] = JsonImpl(M, M.Types[jt]); more = true; }
        }
        foreach (var kv in jsonDone.OrderBy(kv => Mono.Key(kv.Key), StringComparer.Ordinal)) metaTail.Append(kv.Value);
        if (jsonDone.Count > 0)
        {
            // values that reach the serialiser as `object` (Preferences: Dictionary<string, object>) are written by type id
            metaTail.Append("\n/// Registers the member tables above with the host's serialiser for objects held as `object` (by type id).\n/// The driver calls this once at start-up.\npub fn register_json() {\n");
            foreach (var kv in jsonDone.OrderBy(kv => Mono.Key(kv.Key), StringComparer.Ordinal))
            {
                var jt2 = M.Types[kv.Key];
                if (jt2.IsStruct) metaTail.Append($"    terraria_host::json::convert::register_object_writer({jt2.ModPath}::TYPE_ID, |o| unsafe {{ terraria_host::json::convert::ToJToken::to_jtoken(rt::unbox::<{jt2.StructPath}>(o, {jt2.ModPath}::TYPE_ID)) }});\n");
                else if (jt2.TypeId != 0) metaTail.Append($"    terraria_host::json::convert::register_object_writer({jt2.ModPath}::TYPE_ID, |o| <{jt2.StructPath} as terraria_host::json::convert::JsonObject>::to_jtoken(Gc(o.0 as *mut {jt2.StructPath})));\n");
            }
            metaTail.Append("}\n");
        }
        yield return ("meta", "// @generated by tools/cs2rs. Do not edit.\n//! Reflection data of translated types: static fields and attributes of the types whose `typeof` the translated\n//! code takes; instance fields and properties as well for the types the config's `reflect` selects or reaches.\n" + head + M.MetaText() + metaTail);
        var res = new StringBuilder("// @generated by tools/cs2rs. Do not edit.\n//! Thread bodies that have a resumable form (config \"resumable\", DESIGN.md section 8f), by the method id their\n//! `Delegate::from_method` carries. A driver that cannot keep a thread's stack across frames (the browser build)\n//! hands this table to its host, which then runs such a thread as a state machine.\n");
        res.Append("#![allow(unused_imports)]\n" + head);
        res.Append("/// The resumable form of a thread body, given the receiver of the start delegate (`recv`: the object of an\n/// instance method group, 0 for a static one).\npub type Body = fn(usize) -> core::pin::Pin<Box<dyn core::future::Future<Output = ()>>>;\n\n");
        var rts = M.ResumableThreads.OrderBy(k => k.Value, StringComparer.Ordinal).ToList();
        for (int i = 0; i < rts.Count; i++)
            res.Append($"#[allow(unused_variables)]\nfn body_{i}(recv: usize) -> core::pin::Pin<Box<dyn core::future::Future<Output = ()>>> {{\n    Box::pin(async move {{ unsafe {{ {rts[i].Value}.await }} }})\n}}\n\n");
        res.Append("/// (method id, resumable form)\npub static THREADS: &[(u64, Body)] = &[\n");
        for (int i = 0; i < rts.Count; i++) res.Append($"    (0x{rts[i].Key:x}, body_{i}),\n");
        res.Append("];\n");
        yield return ("resumable", res.ToString());
        yield return ("enums", "// @generated by tools/cs2rs. Do not edit.\n//! Name tables of enums whose `ToString()` the translated code calls.\n" + head + M.EnumText()
            + "/// Every enum with a name table.\npub static ALL: &[&rt::EnumInfo] = &[\n" + string.Concat(M.EnumFns.Keys.OrderBy(k => k, StringComparer.Ordinal).Select(k => "    &" + Names.Ident(Names.Snake(k.Replace('.', '_').Replace('+', '_'))).ToUpperInvariant() + "_INFO,\n")) + "];\n");
    }

    SemanticModel Sem(SyntaxTree t) => _models.GetOrAdd(t, x => M.Comp.GetSemanticModel(x));

    static readonly SymbolDisplayFormat SigFmt = new(
        typeQualificationStyle: SymbolDisplayTypeQualificationStyle.NameOnly,
        genericsOptions: SymbolDisplayGenericsOptions.IncludeTypeParameters,
        memberOptions: SymbolDisplayMemberOptions.IncludeParameters | SymbolDisplayMemberOptions.IncludeContainingType,
        parameterOptions: SymbolDisplayParameterOptions.IncludeType | SymbolDisplayParameterOptions.IncludeParamsRefOut,
        miscellaneousOptions: SymbolDisplayMiscellaneousOptions.UseSpecialTypes);

    public static string Display(IMethodSymbol m)
    {
        if (m.MethodKind == MethodKind.PropertyGet) return m.ContainingType.Name + "." + m.AssociatedSymbol.Name + " (get)";
        if (m.MethodKind == MethodKind.PropertySet) return m.ContainingType.Name + "." + m.AssociatedSymbol.Name + " (set)";
        return m.ToDisplayString(SigFmt);
    }
    static string Loc(ISymbol s)
    {
        var l = s.Locations.FirstOrDefault(x => x.IsInSource);
        if (l == null) return "implicit";
        var ls = l.GetLineSpan();
        return Path.GetFileName(ls.Path) + ":" + (ls.StartLinePosition.Line + 1);
    }

    public IOperation BodyOp(IMethodSymbol m, out bool hasSyntax)
    {
        hasSyntax = false;
        var sr = m.DeclaringSyntaxReferences.FirstOrDefault();
        if (sr == null) return null;
        var syn = sr.GetSyntax();
        hasSyntax = true;
        var sem = Sem(syn.SyntaxTree);
        switch (syn)
        {
            case BaseMethodDeclarationSyntax b:
                if (b.Body == null && b.ExpressionBody == null) return null;
                return sem.GetOperation(b);
            case AccessorDeclarationSyntax a:
                if (a.Body == null && a.ExpressionBody == null) return null;
                return sem.GetOperation(a);
            case ArrowExpressionClauseSyntax arrow:
                return sem.GetOperation(arrow) ?? sem.GetOperation(arrow.Expression);
        }
        return null;
    }

    string Sig(TType t, MethodInfo2 mi, string name, out string ret, out List<string> argNames, bool noThis = false)
    {
        var m = mi.Sym;
        var ps = new List<string>(); argNames = new List<string>();
        if (!m.IsStatic && !noThis) { ps.Add($"this: *mut {t.StructPath}"); }
        foreach (var p in m.Parameters)
        {
            var pt = M.RT(p.Type);
            var pn = Names.Ident(p.Name);
            if (pn == "this" || pn == "rt") pn += "_";
            if (t.Consts.Any(c => c.Name == pn)) pn += "_";
            ps.Add(p.RefKind is RefKind.Ref or RefKind.Out ? $"{pn}: *mut {pt}" : $"mut {pn}: {pt}");
            argNames.Add(pn);
        }
        ret = m.ReturnsVoid ? "()" : M.RT(m.ReturnType);
        // never generic: a generic method is one function per instantiation (Mono.cs)
        return $"pub unsafe fn {name}({string.Join(", ", ps)}){(ret == "()" ? "" : " -> " + ret)}";
    }

    MethodReport Report(TType t, IMethodSymbol m) => new() { Type = t, Sym = m, Display = Display(m) };

    void Finish(MethodReport r, Emitter em)
    {
        Merge(r, em);
        if (em.Fails.Count == 0) foreach (var h in em.HostHits) M.Host.Hit(h, Model.FullName(r.Type.Sym));
        r.Status = em.Fails.Count > 0 ? MStatus.Failed : em.Unported.Count > 0 ? MStatus.Unported : MStatus.Clean;
        Reports.Add(r);
    }

    /// Analyse one method without producing a file (dry-run).
    public void Analyse(TType t, MethodInfo2 mi)
    {
        var r = Report(t, mi.Sym);
        if (!mi.Emittable) { r.Status = MStatus.NotEmitted; r.NotEmittedReason = mi.NotEmittedReason; Reports.Add(r); return; }
        if (mi.Sym.IsAbstract) return;
        var op = BodyOp(mi.Sym, out _);
        var em = new Emitter(M, t);
        if (op != null)
        {
            var ret = mi.Sym.ReturnsVoid ? "()" : M.RT(mi.Sym.ReturnType);
            try { em.AppendBody(op, ret); em.Finish(ret); }
            catch (Exception ex) { em.Fails.Add(("internal error: " + ex.GetType().Name, Loc(mi.Sym))); }
            var ls = op.Syntax.GetLocation().GetLineSpan();
            r.Lines = ls.EndLinePosition.Line - ls.StartLinePosition.Line + 1;
        }
        Finish(r, em);
    }

    /// Reports for a type that gets no module (a generic definition nothing instantiates).
    public void ReportOnly(TType t)
    {
        M.Pop(t);
        foreach (var mi in t.Methods) { var r = Report(t, mi.Sym); r.Status = MStatus.NotEmitted; r.NotEmittedReason = t.WholeTypeReason; Reports.Add(r); }
        foreach (var gm in t.Uninstantiated) { var r = Report(t, gm); r.Status = MStatus.NotEmitted; r.NotEmittedReason = t.WholeTypeReason; Reports.Add(r); }
    }

    public string EmitType(TType t, string genModule, string relSource)
    {
        // an instantiation of a generic class: its bodies are written with the definition's type parameters
        using var monoScope = Mono.Enter(t.Map);
        var o = new StringBuilder();
        var sym = t.Sym;
        o.Append("// @generated by tools/cs2rs. Do not edit: change the tool or its config and run it again.\n");
        o.Append($"// C# type `{Model.FullName(sym)}` ({relSource})\n");
        o.Append($"use crate::rt;\nuse crate::rt::*;\nuse crate::s;\nuse crate::{genModule}::*;\n\n");
        // nested type modules are appended by the caller (it knows the tree)
        o.Append("//@@MODS@@\n");
        if (t.WholeTypeReason != null)
        {
            o.Append($"// type not emitted: {t.WholeTypeReason}\n");
            foreach (var mi in t.Methods) { var r = Report(t, mi.Sym); r.Status = MStatus.NotEmitted; r.NotEmittedReason = t.WholeTypeReason; Reports.Add(r); }
            return o.ToString();
        }
        bool isClass = !t.IsStruct && !t.IsStatic && !t.IsInterface;
        if (t.IsInterface)
        {
            o.Append($"/// Interface `{Model.FullName(sym)}`: a value of this type is an `Obj`; calls go through the dispatchers below,\n/// which select the implementation by the object's type id (DESIGN.md section 2).\npub type {t.StructName} = rt::Object;\n\n");
            var impls = M.Ordered.Where(x => x.TypeId != 0 && !x.Sym.IsAbstract && x.WholeTypeReason == null && x.Sym.AllInterfaces.Any(i => SymbolEqualityComparer.Default.Equals(i, sym))).Select(x => $"{x.ModPath}::TYPE_ID").ToList();
            o.Append($"/// Does the type with this id implement `{sym.Name}`? (`is` / `as` / casts)\npub fn implements(id: u32) -> bool {{\n    {(impls.Count == 0 ? "let _ = id;\n    false" : "matches!(id, " + string.Join(" | ", impls) + ")")}\n}}\n\n");
            foreach (var mi in t.Methods) EmitInterfaceDispatcher(t, mi, o);
            return o.ToString();
        }
        if (!t.IsStatic) o.Append($"pub const TYPE_ID: u32 = {t.TypeId};\n\n");

        // ---- instance layout
        if (!t.IsStatic)
        {
            // a class with a native base embeds a native value (not `Copy`: it may own memory)
            var nativeBase = M.NativeBaseOf(t);
            // [StructLayout(LayoutKind.Explicit)]: the fields that own their bytes at their offsets; the C# union
            // members that overlay them are pointer casts (Emit.FieldPlace)
            string repr = t.ExplicitSize > 0 ? $"/// Explicit layout ({t.ExplicitSize} bytes): the fields below own their bytes; the other C# fields overlay them.\n#[repr(C, align({t.ExplicitAlign}))]" : "#[repr(C)]";
            o.Append($"/// `{Model.FullName(sym)}` ({Loc(sym)})\n{repr}\n{(nativeBase == null ? "#[derive(Clone, Copy)]\n" : "")}pub struct {t.StructName} {{\n");
            if (t.Base != null) o.Append($"    pub base: {t.Base.StructPath},\n");
            else if (t.NativeBase != null) { var nbr = M.RT(t.NativeBase); o.Append($"    /// native base class `{Model.FullName(t.NativeBase)}`: the native value, embedded (`rt::NativeSlot`)\n    pub base: rt::NativeSlot<{nbr.Substring(3, nbr.Length - 4)}>,\n"); }
            else if (t.ExcKind != null) o.Append($"    /// `{t.ExcKind}` (runtime exception object)\n    pub base: rt::Exception,\n");
            else if (isClass && sym.BaseType != null && sym.BaseType.SpecialType != SpecialType.System_Object)
                o.Append($"    // base class `{Model.FullName(sym.BaseType)}` is not translated: its fields are missing\n");
            int layoutAt = 0, pads = 0;
            foreach (var f in t.InstFields)
            {
                if (f.RustType == null) o.Append($"    // omitted `{f.DeclName}`: {Model.Short(f.DeclType)} has no Rust representation\n");
                else
                {
                    if (t.ExplicitSize > 0)
                    {
                        // [FieldOffset]: padding up to the field's offset
                        if (f.Offset > layoutAt) o.Append($"    pub __pad{pads++}: [u8; {f.Offset - layoutAt}],\n");
                        layoutAt = f.Offset + f.Size;
                    }
                    o.Append($"    pub {f.Name}: {f.RustType},\n");
                }
            }
            if (t.ExplicitSize > layoutAt) o.Append($"    pub __pad{pads++}: [u8; {t.ExplicitSize - layoutAt}],\n");
            o.Append("}\n");
            // the size is laid out for 64-bit pointers (IntPtr fields of the Windows interop structs); a 32-bit target
            // (the wasm32 browser build, which never runs that interop) gets other sizes
            if (t.ExplicitSize > 0) o.Append($"#[cfg(target_pointer_width = \"64\")]\nconst _: () = assert!(core::mem::size_of::<{t.StructName}>() == {t.ExplicitSize});\n");
            string baseTy = t.Base != null ? t.Base.StructPath : t.NativeBase != null ? $"rt::NativeSlot<{M.RT(t.NativeBase).Substring(3, M.RT(t.NativeBase).Length - 4)}>" : t.ExcKind != null ? "rt::Exception" : null;
            EmitTrace(o, t.StructName, t.InstFields, baseTy, (t.IsStruct ? "    const BOX: rt::BoxKind = rt::BoxKind::Value(TYPE_ID);\n" : "") + ObjectVirtuals(t));
            if (t.IsStruct) EmitKey(o, t);
            o.Append('\n');
        }

        // ---- constants
        foreach (var c in t.Consts)
        {
            if (c.RustType == null || !c.Sym.HasConstantValue) continue;
            var em = new Emitter(M, t);
            o.Append($"pub const {c.Name}: {c.RustType} = {em.ConstText(c.Sym.ConstantValue, c.Sym.Type)};\n");
        }
        if (t.Consts.Count > 0) o.Append('\n');

        // ---- statics
        var statics = t.StaticFields.Where(f => f.RustType != null).ToList();
        var cctorSym = sym.StaticConstructors.FirstOrDefault(c => !c.IsImplicitlyDeclared);
        // a partial type (member filter) only gets its static constructor when the config asks for ".cctor"
        bool cctorExcluded = cctorSym != null && t.Cfg?.Members != null && !t.Cfg.Members.Contains(".cctor");
        if (cctorExcluded) cctorSym = null;
        bool hasStatics = statics.Count > 0 || cctorSym != null;
        t.HasStatics = hasStatics;
        if (hasStatics)
        {
            o.Append("pub struct Statics {\n");
            foreach (var f in t.StaticFields)
            {
                if (f.RustType == null) o.Append($"    // omitted `{f.DeclName}`: {Model.Short(f.DeclType)} has no Rust representation\n");
                else o.Append($"    pub {f.Name}: {f.RustType},\n");
            }
            o.Append("}\n");
            o.Append("static mut __S: core::mem::MaybeUninit<Statics> = core::mem::MaybeUninit::zeroed();\nstatic mut __S_STATE: u8 = 0;\n\n");
            var traced = t.StaticFields.Where(f => f.RustType != null && NeedsTrace(f.RustType)).ToList();
            o.Append("/// Collector root: the handles in the static fields.\nunsafe fn __trace_statics(m: &mut rt::Marker) {\n");
            if (traced.Count > 0) o.Append("    let s = &*(core::ptr::addr_of!(__S) as *const Statics);\n");
            foreach (var f in traced) o.Append($"    rt::Trace::trace(&s.{f.Name}, m);\n");
            o.Append("}\n\n");
            o.Append("/// The class's static fields. Runs the static initialiser on first use (DESIGN.md section 3).\n#[inline(always)]\npub unsafe fn s() -> *mut Statics {\n    if __S_STATE == 0 {\n        cctor();\n    }\n    core::ptr::addr_of_mut!(__S) as *mut Statics\n}\n\n");
            var em = new Emitter(M, t);
            var r = new MethodReport { Type = t, Sym = cctorSym ?? sym.StaticConstructors.FirstOrDefault(), Display = sym.Name + "..cctor (static field initialisers" + (cctorSym != null ? " + static constructor)" : ")"), Key = t.ModPath + "::cctor" };
            em.StaticsPath = "self::s()";
            em.Method = cctorSym ?? sym.StaticConstructors.FirstOrDefault();
            em.Raw("__S_STATE = 1;");
            em.Raw("rt::enter();");
            em.Raw("rt::register_statics(__trace_statics);");
            // no yield to another fiber while the class is half initialised (rt::threads)
            em.Raw("let __cctor = rt::CctorGuard::enter();");
            // [ThreadStatic] fields: one value per thread (rt::threads)
            foreach (var f in t.StaticFields)
                if (f.RustType != null && f.Sym != null && f.Sym.GetAttributes().Any(a => a.AttributeClass?.Name == "ThreadStaticAttribute"))
                    em.Raw($"rt::register_thread_static(core::ptr::addr_of_mut!((*(core::ptr::addr_of_mut!(__S) as *mut Statics)).{f.Name}));");
            if (t.Cfg?.Members != null)
            {
                int excludedS = sym.GetMembers().OfType<IFieldSymbol>().Count(f => f.IsStatic && !f.IsConst && !t.Included(f));
                if (excludedS > 0 || cctorExcluded)
                {
                    var gap = $"{sym.Name}: {excludedS} static fields{(cctorExcluded ? " and the static constructor" : "")} excluded by the config (their initialisers do not run)";
                    em.Raw($"rt::gap({Q(gap)});");
                    em.Unported.Add(gap);
                }
            }
            foreach (var (member, init) in Initializers(sym, true))
            {
                var fi = M.Field(t, member);
                if (fi == null) continue;
                if (fi.RustType == null) { em.Fails.Add(("static field of a type with no Rust representation", Loc(member))); continue; }
                em.Raw($"// {Loc(member)}");
                em.AssignInit($"(*self::s()).{fi.Name}", init);
            }
            if (cctorSym != null)
            {
                var op = BodyOp(cctorSym, out _);
                if (op != null) em.AppendBody(op, "()");
            }
            var body = em.Finish("()");
            o.Append($"/// `{sym.Name}..cctor` ({Loc(sym)})\n#[cold]\n#[inline(never)]\nunsafe fn cctor() {{\n");
            if (em.Fails.Count > 0)
            {
                o.Append("    __S_STATE = 1;\n    rt::register_statics(__trace_statics);\n");
                o.Append($"    rt::unported_method::<()>({Q(sym.Name + "..cctor")}, {Q(em.Fails[0].kind + " at " + em.Fails[0].where)})\n");
            }
            else o.Append(body);
            o.Append("}\n\n");
            if (r.Sym != null || true) { r.Sym ??= null; FinishStatic(r, em); }
        }

        // ---- field initialisers
        bool needInit = !t.IsStatic && !t.IsStruct;
        if (needInit)
        {
            var em = new Emitter(M, t);
            foreach (var (member, init) in Initializers(sym, false))
            {
                var fi = M.Field(t, member);
                if (fi == null) continue;
                if (fi.RustType == null) { em.Fails.Add(("field of a type with no Rust representation", Loc(member))); continue; }
                em.AssignInit(InstPlace("(*this)", fi), init);
            }
            int excluded = t.Cfg?.Members == null ? 0 : sym.GetMembers().OfType<IFieldSymbol>().Count(f => !f.IsStatic && !f.IsConst && !t.Included(f));
            var body = em.Finish("()");
            o.Append($"/// Instance field initialisers of `{sym.Name}` in source order.\npub unsafe fn init_fields(this: *mut {t.StructPath}) {{\n");
            if (excluded > 0)
            {
                var gap = $"{sym.Name}: {excluded} instance fields excluded by the config (their initialisers do not run)";
                o.Append($"    rt::gap({Q(gap)});\n");
                em.Unported.Add(gap);
            }
            if (em.Fails.Count > 0) o.Append($"    rt::unported_method::<()>({Q(sym.Name + " field initialisers")}, {Q(em.Fails[0].kind + " at " + em.Fails[0].where)})\n");
            else o.Append(body);
            o.Append("}\n\n");
            FinishStatic(new MethodReport { Type = t, Display = sym.Name + " instance field initialisers", Key = t.ModPath + "::init_fields" }, em);
        }

        // ---- methods
        foreach (var mi in t.Methods) EmitMethod(t, mi, o, cctorSym != null && hasStatics);
        foreach (var gm in t.Uninstantiated)
        {
            o.Append($"// not emitted: `{Display(gm)}` ({Loc(gm)}): generic method with no closed instantiation in the program\n\n");
            var ur = Report(t, gm); ur.Status = MStatus.NotEmitted; ur.NotEmittedReason = "generic method with no closed instantiation in the program"; Reports.Add(ur);
        }

        // ---- virtual dispatchers
        foreach (var mi in t.Methods) EmitDispatcher(t, mi, o);

        if (t.Cfg != null && t.Cfg.Reflect && !t.IsStatic) EmitReflect(t, o);
        return o.ToString();
    }

    /// The emitter's sets into the report: everything the body reaches, and separately what only dead branches reach.
    static void Merge(MethodReport r, Emitter em)
    {
        r.Fails.AddRange(em.Fails); r.Stubs.AddRange(em.Stubs);
        foreach (var x in em.DeadUnported) { if (em.Unported.Add(x)) r.DeadUnported.Add(x); }
        foreach (var x in em.DeadGaps) em.Gaps.Add(x);
        foreach (var x in em.DeadHostCalls) { if (em.HostCalls.Add(x)) r.DeadHostCalls.Add(x); }
        foreach (var x in em.DeadCalls) { if (em.Calls.Add(x)) r.DeadCalls.Add(x); }
        r.Unported.AddRange(em.Unported); r.HostCalls.AddRange(em.HostCalls);
        r.Gaps.AddRange(em.Gaps); r.Calls.AddRange(em.Calls);
    }

    void FinishStatic(MethodReport r, Emitter em)
    {
        Merge(r, em);
        if (em.Fails.Count == 0) foreach (var h in em.HostHits) M.Host.Hit(h, Model.FullName(r.Type.Sym));
        r.Status = em.Fails.Count > 0 ? MStatus.Failed : em.Unported.Count > 0 ? MStatus.Unported : MStatus.Clean;
        Reports.Add(r);
    }

    internal static string Q(string s) => "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", " ") + "\"";

    /// Field / auto-property initialisers in source order.
    public IEnumerable<(ISymbol member, IOperation value)> Initializers(INamedTypeSymbol sym, bool isStatic)
    {
        foreach (var m in sym.GetMembers())
        {
            if (m.IsStatic != isStatic) continue;
            if (m is IFieldSymbol f && !f.IsConst && f.AssociatedSymbol == null)
            {
                foreach (var sr in f.DeclaringSyntaxReferences)
                    if (sr.GetSyntax() is VariableDeclaratorSyntax vd && vd.Initializer != null)
                    {
                        var op = Sem(vd.SyntaxTree).GetOperation(vd.Initializer);
                        var val = op is IFieldInitializerOperation fi ? fi.Value : op is IVariableInitializerOperation vi ? vi.Value : null;
                        if (val != null) yield return (f, val);
                    }
            }
            else if (m is IPropertySymbol p)
            {
                foreach (var sr in p.DeclaringSyntaxReferences)
                    if (sr.GetSyntax() is PropertyDeclarationSyntax pd && pd.Initializer != null)
                    {
                        var op = Sem(pd.SyntaxTree).GetOperation(pd.Initializer);
                        var val = op is IPropertyInitializerOperation pi ? pi.Value : null;
                        var bf = sym.GetMembers().OfType<IFieldSymbol>().FirstOrDefault(x => SymbolEqualityComparer.Default.Equals(x.AssociatedSymbol, p));
                        if (val != null && bf != null) yield return (bf, val);
                    }
            }
        }
    }

    void EmitMethod(TType t, MethodInfo2 mi, StringBuilder o, bool preciseInit)
    {
        var m = mi.Sym;
        var r = Report(t, m);
        r.Key = t.ModPath + "::" + mi.Name;
        string doc = $"/// `{Display(m)}` ({Loc(m)})\n";
        if (!mi.Emittable)
        {
            o.Append($"// not emitted: `{Display(m)}` ({Loc(m)}): {mi.NotEmittedReason}\n\n");
            r.Status = MStatus.NotEmitted; r.NotEmittedReason = mi.NotEmittedReason; Reports.Add(r);
            return;
        }
        if (m.IsAbstract) return; // only the dispatcher exists
        // one instantiation of a generic method: the body is written with the method's type parameters
        using var methodScope = mi.Open == null ? default : Mono.Enter(Merge(t.Map, Mono.MapOf(null, m)));
        var sig = Sig(t, mi, mi.Name, out var ret, out var argNames);
        var em = new Emitter(M, t) { Method = mi.Open ?? m };
        var op = BodyOp(mi.Open ?? m, out bool hasSyntax);
        bool isCtor = m.MethodKind == MethodKind.Constructor;
        string body;
        if (preciseInit && (m.IsStatic || isCtor)) em.Raw("self::s();");
        if (m.IsStatic || isCtor) em.Calls.Add(t.ModPath + "::cctor");
        if (isCtor && !t.IsStruct) em.Calls.Add(t.ModPath + "::init_fields");
        if (isCtor)
        {
            bool chainsThis = op is IConstructorBodyOperation { Initializer: IExpressionStatementOperation { Operation: IInvocationOperation ci } } && SymbolEqualityComparer.Default.Equals(Mono.Sub(ci.TargetMethod.ContainingType), t.Sym);
            bool explicitInit = op is IConstructorBodyOperation { Initializer: not null };
            if (!t.IsStruct && !chainsThis) em.Raw("init_fields(this);");
            if (!t.IsStruct && !explicitInit)
            {
                var bt = t.Sym.BaseType;
                if (t.Base != null)
                {
                    var bc = bt.InstanceConstructors.FirstOrDefault(c => c.Parameters.Length == 0) ?? bt.InstanceConstructors.FirstOrDefault(c => c.Parameters.All(p => p.IsOptional));
                    var bmi = bc == null ? null : M.Method(t.Base, bc.OriginalDefinition);
                    if (bmi != null && bmi.Emittable && bc.Parameters.Length == 0) em.Raw($"{t.Base.ModPath}::{bmi.Name}(this as *mut {t.Base.StructPath});");
                    else if (bmi != null && bmi.Emittable)
                    {
                        // implicit base call that relies on optional parameters
                        var vals = bc.Parameters.Select(p => em.ConstText(p.ExplicitDefaultValue, p.Type));
                        em.Raw($"{t.Base.ModPath}::{bmi.Name}(this as *mut {t.Base.StructPath}, {string.Join(", ", vals)});");
                    }
                    else { em.Unported.Add(bt.Name + "..ctor"); em.Raw($"rt::gap({Q(bt.Name + "..ctor")});"); }
                }
                else if (t.ExcKind != null) em.Raw($"rt::exc_init(this as *mut rt::Exception, {Q(t.ExcKind)}, Str::NULL);");
                else if (t.NativeBase != null)
                {
                    // implicit `: base()` of a native base class: its parameterless constructor template
                    var nbc = t.NativeBase.InstanceConstructors.FirstOrDefault(c => c.Parameters.Length == 0);
                    em.Raw(em.NativeBaseInit(nbc, new List<string>(), null) + ";");
                }
                else if (bt != null && bt.SpecialType != SpecialType.System_Object && bt.InstanceConstructors.FirstOrDefault(c => c.Parameters.Length == 0) is { } ibc && M.Cfg.Inert.ContainsKey(M.DocId(ibc.OriginalDefinition)))
                    em.Raw($"{M.Cfg.HostRoot}::inert({Q(bt.Name + "..ctor")});");
                else if (bt != null && bt.SpecialType != SpecialType.System_Object)
                { em.Unported.Add(bt.Name + "..ctor (base class not translated)"); em.Raw($"rt::gap({Q(bt.Name + "..ctor (base class not translated)")});"); }
            }
        }
        if (isCtor && op != null && t.Cfg?.Members != null && !t.Cfg.Members.Contains(".ctor"))
        {
            // partial type: the constructor body touches members the config left out
            var gap = $"{t.Sym.Name}..ctor: constructor body excluded by the config";
            em.Unported.Add(gap);
            em.Raw($"rt::gap({Q(gap)});");
        }
        else if (!isCtor && M.Cfg.Bodies.TryGetValue(M.DocId((mi.Open ?? m).OriginalDefinition), out var customBody))
        {
            // config "bodies": hand-written replacement of this method's body
            for (int ti = 0; ti < m.TypeArguments.Length; ti++) customBody = customBody.Replace("{T" + ti + "}", M.RT(m.TypeArguments[ti]) ?? "()");
            em.Raw("// body replaced by the translator config (\"bodies\")");
            em.Raw(ret == "()" ? customBody + ";" : "return " + customBody + ";");
        }
        else if (op != null)
        {
            try { em.AppendBody(op, ret); }
            catch (Exception ex) { em.Fails.Add(("internal error: " + ex.GetType().Name + " " + ex.Message, Loc(m))); }
            var ls = op.Syntax.GetLocation().GetLineSpan();
            r.Lines = ls.EndLinePosition.Line - ls.StartLinePosition.Line + 1;
        }
        else if (m.AssociatedSymbol is IPropertySymbol prop && hasSyntax)
        {
            // auto-property accessor
            var bf = t.Sym.GetMembers().OfType<IFieldSymbol>().FirstOrDefault(x => SymbolEqualityComparer.Default.Equals(x.AssociatedSymbol, prop));
            var fi = bf == null ? null : M.Field(t, bf);
            if (fi == null || fi.RustType == null) em.Fails.Add(("auto-property without a representable backing field", Loc(m)));
            else
            {
                string place = m.IsStatic ? $"(*self::s()).{fi.Name}" : InstPlace("(*this)", fi);
                em.Raw(m.MethodKind == MethodKind.PropertyGet ? $"return {place};" : $"{place} = {argNames[^1]};");
            }
        }
        else if (m.MethodKind is MethodKind.EventAdd or MethodKind.EventRemove && m.AssociatedSymbol is IEventSymbol fev)
        {
            // accessor of a field-like event: combine into / remove from the delegate field
            var fi = M.Field(t, fev);
            if (fi == null || fi.RustType == null) em.Fails.Add(("event accessor without a representable delegate field", Loc(m)));
            else
            {
                string place = m.IsStatic ? $"(*self::s()).{fi.Name}" : InstPlace("(*this)", fi);
                em.Raw($"let __p = core::ptr::addr_of_mut!({place});");
                em.Raw($"*__p = Delegate::{(m.MethodKind == MethodKind.EventAdd ? "combine" : "remove")}(*__p, {argNames[^1]});");
            }
        }
        else if (!isCtor) em.Fails.Add((m.IsExtern ? "extern method" : "method without a body", Loc(m)));
        body = em.Finish(ret);
        o.Append(doc).Append(sig).Append(" {\n");
        if (em.Fails.Count > 0)
            o.Append($"    rt::unported_method::<{ret}>({Q(Display(m))}, {Q(em.Fails[0].kind + " at " + em.Fails[0].where)})\n");
        else o.Append(body);
        o.Append("}\n\n");
        if (M.TwinF64(m))
        {
            // float mode "jit32": the same body with its return values unrounded (Model.TwinF64); where the twin
            // cannot be emitted it is the rounded result widened (exactly what the call gave before)
            var tsig = Sig(t, mi, mi.Name + "__x87", out _, out var targs);
            tsig = tsig.Substring(0, tsig.LastIndexOf(" -> ", StringComparison.Ordinal)) + " -> f64";
            string tbody = null;
            if (em.Fails.Count == 0 && op != null)
            {
                var tem = new Emitter(M, t) { Method = mi.Open ?? m, TwinF64 = true };
                if (preciseInit && m.IsStatic) tem.Raw("self::s();");
                try { tem.AppendBody(op, "f64"); } catch (Exception ex) { tem.Fails.Add(("internal error: " + ex.GetType().Name + " " + ex.Message, Loc(m))); }
                var tb = tem.Finish("f64");
                if (tem.Fails.Count == 0) tbody = tb;
            }
            var plain = $"{mi.Name}({string.Join(", ", (m.IsStatic ? new string[0] : new[] { "this" }).Concat(targs))})";
            o.Append($"/// `{Display(m)}` with its float result unrounded: the value the original's caller continues with (ST0)\n").Append(tsig).Append(" {\n");
            o.Append(tbody ?? $"    {plain} as f64\n");
            o.Append("}\n\n");
        }
        if (M.ArgTwinParams(m) is { Count: > 0 } up && op != null)
        {
            // float mode "jit32": the body as a caller that inlined it runs it, with the float parameters it never
            // writes holding the caller's unrounded x87 value (Model.ArgTwinParams; FLOAT_RULE.md section 10, item 26):
            // `name__u`, and `name__u__x87` with the unrounded result too. Where the twin cannot be emitted it rounds
            // those parameters and calls the plain method
            foreach (bool x87 in M.TwinF64(m) ? new[] { false, true } : new[] { false })
            {
                var usig = Sig(t, mi, mi.Name + (x87 ? "__u__x87" : "__u"), out _, out var uargs);
                var wideParams = new HashSet<ISymbol>(up.Select(i => (ISymbol)m.Parameters[i]), SymbolEqualityComparer.Default);
                foreach (int i in up) usig = usig.Replace($"mut {uargs[i]}: f32", $"mut {uargs[i]}__u: f64");
                if (x87) usig = usig.Substring(0, usig.LastIndexOf(" -> ", StringComparison.Ordinal)) + " -> f64";
                var uret = x87 ? "f64" : ret;
                var uem = new Emitter(M, t) { Method = mi.Open ?? m, TwinF64 = x87, WideParams = wideParams };
                if (preciseInit && m.IsStatic) uem.Raw("self::s();");
                string ubody = null;
                if (em.Fails.Count == 0)
                {
                    try { uem.AppendBody(op, uret); } catch (Exception ex) { uem.Fails.Add(("internal error: " + ex.GetType().Name + " " + ex.Message, Loc(m))); }
                    var ub = uem.Finish(uret);
                    if (uem.Fails.Count == 0) ubody = ub;
                }
                var pro = new StringBuilder();
                foreach (int i in up)
                    pro.Append(ubody != null && uem.ParamIsWide(m.Parameters[i]) ? $"    let mut {uargs[i]}: f64 = {uargs[i]}__u;\n" : $"    let mut {uargs[i]}: f32 = {uargs[i]}__u as f32;\n");
                var uplain = $"{mi.Name}{(x87 ? "__x87" : "")}({string.Join(", ", (m.IsStatic ? new string[0] : new[] { "this" }).Concat(uargs))})";
                o.Append($"/// `{Display(m)}` inlined by a caller of the reference runs: float parameters {string.Join(", ", up.Select(i => m.Parameters[i].Name))} unrounded (the caller's x87 value){(x87 ? ", float result unrounded" : "")}\n").Append(usig).Append(" {\n");
                o.Append(pro);
                o.Append(ubody ?? $"    {uplain}\n");
                o.Append("}\n\n");
            }
        }
        if (M.VecTwin(m) && op != null)
        {
            // float mode "jit32": the body as a caller that inlined it compiled it (jit_vec_ctx.tsv: its Vector2
            // operators called or inlined there); where the twin cannot be emitted it is the plain method
            var sigs = M.VecCtxSigs(Model.ClrMethodKey(m.OriginalDefinition));
            for (int vi = 0; vi < sigs.Count; vi++)
            {
                var vsig = Sig(t, mi, mi.Name + "__vc" + vi, out _, out var vargs);
                var parts = sigs[vi].Split('|');
                var ctx = new Dictionary<string, char>(StringComparer.Ordinal);
                foreach (var e in parts[0].Split(';')) { int eq = e.LastIndexOf('='); if (eq > 0) ctx[e.Substring(0, eq)] = e[eq + 1]; }
                var vem = new Emitter(M, t) { Method = mi.Open ?? m, VecCtx = ctx, VecCtxMode = parts.Length > 1 ? parts[1] : null };
                if (preciseInit && m.IsStatic) vem.Raw("self::s();");
                string vbody = null;
                if (em.Fails.Count == 0)
                {
                    try { vem.AppendBody(op, ret); } catch (Exception ex) { vem.Fails.Add(("internal error: " + ex.GetType().Name + " " + ex.Message, Loc(m))); }
                    var vb = vem.Finish(ret);
                    if (vem.Fails.Count == 0) vbody = vb;
                }
                var vplain = $"{mi.Name}({string.Join(", ", (m.IsStatic ? new string[0] : new[] { "this" }).Concat(vargs))})";
                o.Append($"/// `{Display(m)}` as inlined by a caller of the reference runs: Vector2 operators {sigs[vi].Replace("Microsoft.Xna.Framework.", "")}\n").Append(vsig).Append(" {\n");
                o.Append(vbody ?? $"    {vplain}\n");
                o.Append("}\n\n");
            }
        }
        if (M.IsResumable(m)) EmitResumable(t, mi, o, op, ret, preciseInit);
        if (isCtor && !t.Sym.IsAbstract)
        {
            var nsig = Sig(t, mi, "new" + mi.Name.Substring(4), out _, out var an, true);
            var head = nsig.Substring(0, nsig.LastIndexOf(')'));
            var ps = "";
            if (t.IsStruct)
                o.Append($"/// `new {Display(m)}`\n{head}{ps}) -> {t.StructPath} {{\n    let mut __o: {t.StructPath} = rt::zero();\n    {mi.Name}({string.Join(", ", new[] { "core::ptr::addr_of_mut!(__o)" }.Concat(an))});\n    __o\n}}\n\n");
            else
                o.Append($"/// `new {Display(m)}`\n{head}{ps}) -> Gc<{t.StructPath}> {{\n    let __o = rt::alloc::<{t.StructPath}>(TYPE_ID);\n    {mi.Name}({string.Join(", ", new[] { "__o.0" }.Concat(an))});\n    __o\n}}\n\n");
        }
        Finish(r, em);
    }

    /// The resumable form of a method listed in the config's "resumable" (DESIGN.md section 8f): the same body as
    /// an `async fn` named `X__resumable`. Anything the emitter cannot make resumable stops the translation: a thread
    /// that silently fell back to its plain form would suspend a stack again.
    void EmitResumable(TType t, MethodInfo2 mi, StringBuilder o, IOperation op, string ret, bool preciseInit)
    {
        var m = mi.Sym;
        string where = Display(m) + " (" + Loc(m) + ")";
        if (M.Cfg.Resumable.Sleep == null || M.Cfg.Resumable.Try == null) throw new ConfigException("\"resumable\" needs \"sleep\" and \"try\"");
        // instance methods: of a class, not virtual (the receiver is `this: *mut T`, kept in the machine)
        if (mi.Open != null || m.Parameters.Any(p => p.RefKind != RefKind.None) || m.MethodKind != MethodKind.Ordinary
            || (!m.IsStatic && (t.IsStruct || m.IsVirtual || m.IsAbstract || m.IsOverride)))
            throw new ConfigException($"resumable {where}: only non-generic static methods, or non-virtual methods of a class, without ref / out parameters");
        if (op == null || M.Cfg.Bodies.ContainsKey(M.DocId(m.OriginalDefinition))) throw new ConfigException($"resumable {where}: no translated body");
        var em = new Emitter(M, t) { Method = m, Resumable = true };
        if (preciseInit) em.Raw("self::s();");
        em.AppendBody(op, ret);
        var body = em.Finish(ret);
        if (em.Fails.Count > 0) throw new ConfigException($"resumable {where}: {em.Fails[0].kind} at {em.Fails[0].where}");
        var sig = Sig(t, mi, mi.Name + "__resumable", out _, out _);
        o.Append($"/// `{Display(m)}` as a state machine (config \"resumable\", DESIGN.md section 8f): suspends at `Thread.Sleep`.\n");
        o.Append(sig.Replace("pub unsafe fn ", "pub async unsafe fn ")).Append(" {\n").Append(body).Append("}\n\n");
        if (m.ReturnsVoid && m.Parameters.Length == 0) M.ResumableThreads[M.MethodId(m)] = m.IsStatic ? $"{t.ModPath}::{mi.Name}__resumable()" : $"{t.ModPath}::{mi.Name}__resumable(recv as *mut {t.StructPath})";
    }

    static bool Overrides(IMethodSymbol m, IMethodSymbol root)
    {
        for (var c = m; c != null; c = c.OverriddenMethod)
            if (SymbolEqualityComparer.Default.Equals(c.OriginalDefinition, root.OriginalDefinition)) return true;
        return false;
    }

    static Dictionary<ITypeParameterSymbol, ITypeSymbol> Merge(Dictionary<ITypeParameterSymbol, ITypeSymbol> a, Dictionary<ITypeParameterSymbol, ITypeSymbol> b)
    {
        var m = new Dictionary<ITypeParameterSymbol, ITypeSymbol>(SymbolEqualityComparer.Default);
        if (a != null) foreach (var kv in a) m[kv.Key] = kv.Value;
        if (b != null) foreach (var kv in b) m[kv.Key] = kv.Value;
        return m;
    }

    void EmitDispatcher(TType t, MethodInfo2 mi, StringBuilder o)
    {
        var m = mi.Sym;
        var open = mi.Open ?? m;
        if (!mi.Emittable || m.IsStatic || t.IsStruct || !(open.IsVirtual || open.IsAbstract || open.IsOverride)) return;
        // local root: nothing translated above it
        if (open.OverriddenMethod != null)
        {
            var up = M.Get(open.OverriddenMethod.ContainingType);
            var umi = up == null ? null : M.MethodInst(up, open.OverriddenMethod, mi.TypeArgs);
            if (umi != null && umi.Emittable) return;
        }
        var sig = Sig(t, mi, mi.Name + "__v", out var ret, out var an);
        var arms = new SortedDictionary<string, List<string>>(StringComparer.Ordinal);
        foreach (var x in M.Ordered)
        {
            if (!x.IsClass || x.TypeId == 0 || x == t) continue;
            bool derives = false;
            for (var b = x.Sym.BaseType; b != null; b = b.BaseType) if (SymbolEqualityComparer.Default.Equals(b, t.Sym)) derives = true;
            if (!derives) continue;
            for (var c = x.Sym; c != null && !SymbolEqualityComparer.Default.Equals(c, t.Sym); c = c.BaseType)
            {
                var ov = c.GetMembers(open.Name).OfType<IMethodSymbol>().FirstOrDefault(k => k.IsOverride && Overrides(k, open));
                if (ov == null) continue;
                var ct = M.Get(c); var cmi = ct == null ? null : M.MethodInst(ct, ov, mi.TypeArgs);
                string call = cmi != null && cmi.Emittable && !ov.IsAbstract
                    ? $"{ct.ModPath}::{cmi.Name}({string.Join(", ", new[] { $"this as *mut {ct.StructPath}" }.Concat(an))})"
                    : $"rt::unported::<{ret}>({Q(c.Name + "." + m.Name + " (override not translated)")})";
                if (!arms.TryGetValue(call, out var ids)) arms[call] = ids = new List<string>();
                ids.Add($"{x.ModPath}::TYPE_ID");
                break;
            }
        }
        var dr = new MethodReport { Type = t, Sym = null, Display = Display(m) + " (virtual dispatch)", Key = t.ModPath + "::" + mi.Name + "__v", Status = MStatus.Clean };
        foreach (var k in arms.Keys) { int p = k.IndexOf('('); if (p > 0 && !k.StartsWith("rt::")) dr.Calls.Add(k.Substring(0, p)); }
        if (!open.IsAbstract) dr.Calls.Add(t.ModPath + "::" + mi.Name);
        Dispatchers.Add(dr);
        o.Append($"/// Virtual dispatch of `{Display(m)}` (DESIGN.md section 2).\n{sig} {{\n");
        string self = open.IsAbstract ? $"rt::unported::<{ret}>({Q(Display(m) + " (abstract, no override for this object)")})" : $"{mi.Name}({string.Join(", ", new[] { "this" }.Concat(an))})";
        if (arms.Count == 0) o.Append($"    {self}\n");
        else
        {
            o.Append("    match rt::type_id_of(this as *const u8) {\n");
            foreach (var kv in arms) o.Append($"        {string.Join(" | ", kv.Value)} => {kv.Key},\n");
            o.Append($"        _ => {self},\n    }}\n");
        }
        o.Append("}\n\n");
    }

    /// The place of instance field `fi` of the struct or object at place `at`: a member, or for a union member of
    /// an explicit-layout struct (`FieldInfo2.Overlay`) the bytes at its offset.
    public static string InstPlace(string at, FieldInfo2 fi) =>
        fi.Overlay ? $"(*((core::ptr::addr_of_mut!({at}) as *mut u8).add({fi.Offset}) as *mut {fi.RustType}))" : $"{at}.{fi.Name}";

    /// Can a value of this Rust type hold a collector handle?
    public static bool NeedsTrace(string rt)
    {
        switch (rt)
        {
            case "bool": case "u8": case "i8": case "u16": case "i16": case "u32": case "i32": case "u64": case "i64": case "f32": case "f64": case "()": return false;
        }
        if (rt.StartsWith("terraria_core::xna::")) return false;
        if (rt.StartsWith("Nullable<")) return NeedsTrace(rt.Substring(9, rt.Length - 10));
        return true;
    }

    /// `baseTy`: Rust type of the `base` field (a translated base class, a native base in its slot, the runtime's
    /// exception object), or null. `NEEDS_TRACE` is exact (a struct of structs without handles is not traced, and
    /// stores of it need no barrier); `RESCAN` is false (every store into translated types is behind the barrier,
    /// DESIGN.md section 9) unless an embedded native value asks for it.
    void EmitTrace(StringBuilder o, string name, List<FieldInfo2> fields, string baseTy, string extra)
    {
        bool hasBase = baseTy != null;
        var traced = fields.Where(f => f.RustType != null && NeedsTrace(f.RustType)).ToList();
