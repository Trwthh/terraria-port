                var r = M.RT(mt);
                var jca = m.GetAttributes().FirstOrDefault(a => a.AttributeClass?.Name == "JsonConverterAttribute");
                if (jca != null && jca.ConstructorArguments.Length >= 1 && jca.ConstructorArguments[0].Value is INamedTypeSymbol { Name: "StringEnumConverter" } && Mono.Sub(mt) is INamedTypeSymbol { TypeKind: TypeKind.Enum } sen && m is IFieldSymbol sef && M.Field(c, sef) is { RustType: not null } sefi)
                {
