    /// The Rust side of Newtonsoft's default contract for one game type (`FromJToken` / `ToJToken` for a struct,
    /// `JsonObject` for a class). Rules reproduced (Newtonsoft.Json 10, `DefaultContractResolver`):
    /// members are the public instance fields and the public read/write properties; `[JsonIgnore]` removes one; with
    /// `[JsonObject(MemberSerialization.OptIn)]` (on the type or the nearest base that has the attribute) only
    /// `[JsonProperty]` members count. Order as measured on the game's dll (`terraria-host\tests\dotnet\
    /// achievements_probe.ps1`): all fields, then all properties; within each, the type's own members in declaration
    /// order, then each base class's (most derived first), a base's non-private members before its private ones
    /// (`Type.GetFields` on the derived type, then Newtonsoft's `GetChildPrivateFields`). An object is written by
    /// its RUN-TIME type (a subclass's table). A `[JsonProperty]` member may be private and `readonly`; `[JsonProperty("Name")]` renames; an absent
    /// member keeps the value the constructor gave it; an enum is its number. A class is created with its
    /// parameterless constructor. What the table cannot express stops loudly when that type is (de)serialised, never
    /// silently: a member whose type the host's converter has no rule for, a `[JsonConverter]` on a member other
    /// than `StringEnumConverter` on an enum (the enum's name as text; reading also takes a number), a class with
    /// neither a parameterless constructor nor exactly one public constructor. That one constructor is called as
    /// Newtonsoft calls it: each parameter gets the JSON property of the PARAMETER's name (ignoring case) or its
    /// default, and the members are set from their properties afterwards (`WorldGenRange(int minimum, int
    /// maximum)` with `[JsonProperty("Min")] readonly int Minimum`: constructed with 0, 0, then `Min` is stored).
    static string JsonImpl(Model M, TType tt)
    {
        using var scope = Mono.Enter(tt.Map);
        const string C = "terraria_host::json::convert";
        const string J = "Gc<terraria_host::json::token::JToken>";
        string full = Model.FullName(tt.Sym);
        string Loud(string what) => $"crate::host::unimplemented_value::<()>({Q("Newtonsoft.Json: " + full + ": " + what)});";
        static bool Has(ISymbol m, string attr) => m.GetAttributes().Any(a => a.AttributeClass?.Name == attr);
        // can the host converter read / write a value of this type?
        bool Convertible(ITypeSymbol t)
        {
            t = Mono.Sub(t);
            if (t.SpecialType is SpecialType.System_Boolean or SpecialType.System_Byte or SpecialType.System_SByte or SpecialType.System_Int16 or SpecialType.System_UInt16 or SpecialType.System_Int32 or SpecialType.System_UInt32 or SpecialType.System_Int64 or SpecialType.System_UInt64 or SpecialType.System_Single or SpecialType.System_Double or SpecialType.System_String or SpecialType.System_Object) return true;
            if (t is IArrayTypeSymbol at) return at.Rank == 1 && Convertible(at.ElementType);
            if (t is not INamedTypeSymbol n) return false;
            if (n.TypeKind == TypeKind.Enum) return M.RT(n) == "i32";
            if (n.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T) return Convertible(n.TypeArguments[0]);
            var od = n.OriginalDefinition.ToDisplayString();
            if (od == "System.Collections.Generic.List<T>") return Convertible(n.TypeArguments[0]);
            if (od == "System.Collections.Generic.Dictionary<TKey, TValue>") return n.TypeArguments[0].SpecialType == SpecialType.System_String && Convertible(n.TypeArguments[1]);
            if (od.StartsWith("Newtonsoft.Json.Linq.J")) return M.RT(n) == J;
            if (M.JsonTypes.ContainsKey(n)) return true;
            if (M.Types.TryGetValue(n, out var nt) && nt.WholeTypeReason == null && !nt.IsInterface && !nt.IsStatic && n.TypeKind is TypeKind.Class or TypeKind.Struct && M.RT(n) != null)
            {
                M.JsonTypes.TryAdd(n, true);
                return true;
            }
            return false;
        }
        var chain = new List<TType>();
        for (var c = tt; c != null; c = M.Pop(c).Base) chain.Add(c);
        // [JsonObject] is inherited: the nearest one in the chain decides
        bool optIn = false;
        foreach (var c in chain)
        {
            var joa = c.Sym.GetAttributes().FirstOrDefault(a => a.AttributeClass?.Name == "JsonObjectAttribute");
            if (joa == null) continue;
            optIn = joa.ConstructorArguments.Length == 1 && joa.ConstructorArguments[0].Value is int ms && ms == 1;
            break;
        }
        string self = tt.IsStruct ? "o" : "(*o.ptr())";
        // (is a property, distance from the type, private member of a base, declaration index) -> read / write text
        var entries = new List<(int kind, int depth, int priv, int decl, StringBuilder read, StringBuilder write)>();
        for (int depth = 0; depth < chain.Count; depth++)
        {
            var c = chain[depth];
            string at = tt.IsStruct || c == tt ? self : $"(*(o.0 as *mut {c.StructPath}))";
            int decl = 0;
            foreach (var m in c.Sym.GetMembers())
            {
                decl++;
                var read = new StringBuilder(); var write = new StringBuilder();
                entries.Add((m is IPropertySymbol ? 1 : 0, depth, depth > 0 && m.DeclaredAccessibility == Accessibility.Private ? 1 : 0, decl, read, write));
                if (m.IsStatic || m.IsImplicitlyDeclared) continue;
                if (m is not (IFieldSymbol or IPropertySymbol)) continue;
                if (m is IFieldSymbol { AssociatedSymbol: not null }) continue;
                if (m is IPropertySymbol { IsIndexer: true }) continue;
                bool jp = Has(m, "JsonPropertyAttribute");
                if (Has(m, "JsonIgnoreAttribute")) continue;
                bool isPublic = m.DeclaredAccessibility == Accessibility.Public;
                // a property is written when it has a public getter (also a get-only one: `WorldManifest.FinalHash`) and
                // read when it has a setter too; a property without a public getter needs [JsonProperty]
                if (m is IPropertySymbol pp0 && !jp && (pp0.GetMethod == null || pp0.GetMethod.DeclaredAccessibility != Accessibility.Public)) continue;
                if (optIn ? !jp : !(isPublic || jp)) continue;
                string name = m.Name;
                var jpa = m.GetAttributes().FirstOrDefault(a => a.AttributeClass?.Name == "JsonPropertyAttribute");
                if (jpa != null && jpa.ConstructorArguments.Length == 1 && jpa.ConstructorArguments[0].Value is string rn) name = rn;
                if (jpa != null) foreach (var na in jpa.NamedArguments) if (na.Key == "PropertyName" && na.Value.Value is string rn2) name = rn2;
