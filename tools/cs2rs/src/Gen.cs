                    if (fi == null || fi.RustType == null) { var l = Loud($"field {m.Name} is not representable"); read.Append($"        {l}\n"); write.Append($"        {l}\n"); continue; }
                    read.Append($"        if let Some(v) = {C}::member::<{r}>(t, {Q(name)}) {{ {InstPlace(at, fi)} = v; }}\n");
                    write.Append($"        {C}::set_member(j, {Q(name)}, {InstPlace(at, fi)});\n");
                }
                else
                {
                    var p = (IPropertySymbol)m;
                    var gm = p.GetMethod == null ? null : M.Method(c, p.GetMethod); var sm = p.SetMethod == null ? null : M.Method(c, p.SetMethod);
                    string recv = tt.IsStruct ? "core::ptr::addr_of_mut!(o)" : $"o.0 as *mut {c.StructPath}";
                    if (p.SetMethod == null) { /* get-only: Newtonsoft ignores the JSON property */ }
                    else if (sm != null && sm.Emittable) read.Append($"        if let Some(v) = {C}::member::<{r}>(t, {Q(name)}) {{ {c.ModPath}::{sm.Name}({recv}, v); }}\n");
                    else read.Append($"        if {C}::has_member(t, {Q(name)}) {{ {Loud($"property {m.Name} has no translated setter")} }}\n");
                    if (gm != null && gm.Emittable) write.Append($"        {C}::set_member(j, {Q(name)}, {c.ModPath}::{gm.Name}({recv}));\n");
                    else write.Append($"        {Loud($"property {m.Name} has no translated getter")}\n");
                }
            }
        }
        var readAll = new StringBuilder(); var writeAll = new StringBuilder();
        foreach (var e in entries.OrderBy(e => e.kind).ThenBy(e => e.depth).ThenBy(e => e.priv).ThenBy(e => e.decl)) { readAll.Append(e.read); writeAll.Append(e.write); }
        {
            var read = readAll; var write = writeAll;
            return JsonImplText(M, tt, full, read, write);
        }
    }

