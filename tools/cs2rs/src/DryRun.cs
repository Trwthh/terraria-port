// Dry run: run the emitter over whole classes without writing Rust, and report what it cannot translate yet.
using System.Diagnostics;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Cs2Rs;

public static class DryRun
{
    /// Collapse details (type names, method names) so that reasons group.
    public static string Group(string kind)
    {
        if (kind == null) return "?";
        kind = Regex.Replace(kind, @" \(.*\)$", "");
        kind = Regex.Replace(kind, @"^(internal error: \w+).*$", "$1");
        kind = Regex.Replace(kind, @"^(signature uses a type with no Rust representation): .*$", "$1");
        kind = Regex.Replace(kind, @"^(type with no Rust representation): .*$", "$1");
        kind = Regex.Replace(kind, @"^(foreach over) .*$", "$1 a type without a mapped enumerator");
        kind = Regex.Replace(kind, @"^(reference conversion) .*$", "$1 with no mapping");
        kind = Regex.Replace(kind, @"^(ToString\(\) of) .*$", "$1 a non-primitive in a concatenation");
        kind = Regex.Replace(kind, @"^(field of a type with no Rust representation): .*$", "$1");
        kind = Regex.Replace(kind, @"^(creation of a type with no Rust representation): .*$", "$1");
        kind = Regex.Replace(kind, @"^(call returning a type with no Rust representation): .*$", "$1");
        kind = Regex.Replace(kind, @"^(receiver type with no Rust representation): .*$", "$1");
        kind = Regex.Replace(kind, @"^(conversion) .* -> .*$", "$1 with no rule");
        kind = Regex.Replace(kind, @"^(binary operator \w+) on .*$", "$1 on a non-numeric type");
        kind = Regex.Replace(kind, @"^(compound assignment on) .*$", "$1 a non-numeric type");
        kind = Regex.Replace(kind, @"^(switch on) .*$", "$1 a non-integral type");
        kind = Regex.Replace(kind, @"^(constant pattern on) .*$", "$1 a non-primitive");
        kind = Regex.Replace(kind, @"^(\+\+ / -- on) .*$", "$1 a non-numeric type");
        return kind;
    }
    static string Detail(string kind)
    {
        var m = Regex.Match(kind ?? "", @"\((.*)\)$");
        return m.Success ? m.Groups[1].Value : null;
    }

    public static int Run(Config cfg, CSharpCompilation comp, List<string> typeNames, string coverage, int errorCount, Stopwatch sw, bool all = false)
    {
        if (all) return RunAll(cfg, comp, coverage, errorCount, sw);
        var model = new Model(cfg, comp, true);
        var gen = new Gen(model);
        var perType = new List<(string name, List<TType> types)>();
        foreach (var n in typeNames)
        {
            var sym = Program.FindType(comp, n);
            if (sym == null) { Console.Error.WriteLine("error: type not found: " + n); return 1; }
            var list = new List<TType>();
            void Add(INamedTypeSymbol s)
            {
                var t = model.Get(s);
                if (t != null) { model.Pop(t); list.Add(t); }
                foreach (var nt in s.GetTypeMembers()) if (nt.TypeKind is TypeKind.Class or TypeKind.Struct) Add(nt);
            }
            Add(sym);
            perType.Add((n, list));
        }
        var work = perType.SelectMany(p => p.types.SelectMany(t => t.Methods.Select(m => (t, m)))).ToList();
        Program.ParallelBig(Enumerable.Range(0, work.Count).ToList(), Program.Dop, k => gen.Analyse(work[k].t, work[k].m));
        var reports = gen.Reports.ToList();
        var sb = new StringBuilder("# cs2rs coverage (dry run)\n\n");
        sb.Append("Generated by `cs2rs --dry-run ... --coverage COVERAGE.md`. Do not edit by hand; the section \"What is tested\" at the end is appended from `coverage_tail.md`.\n\n");
        sb.Append("The dry run feeds every method of the listed classes (nested types included) through the same emitter as the pilot, with every type declared in the decompile treated as translated, and records each construct the emitter refuses. ");
        sb.Append("\"Can translate today\" means the emitter produced a body with no refusal. It does **not** mean the body was compiled by rustc or run: only the pilot classes are. ");
        sb.Append("Calls into library types (.NET, XNA, ReLogic) that have no entry in the config count as refusals here, because each one needs a runtime function.\n\n");
        if (errorCount >= 0) sb.Append($"Roslyn compilation of the decompile: {errorCount} errors.\n\n");
        sb.Append("| class | methods | can translate today | % | source lines in those | % of lines | refused | no Rust signature |\n|---|---:|---:|---:|---:|---:|---:|---:|\n");
        int T = 0, OK = 0; long LT = 0, LOK = 0;
        foreach (var (name, types) in perType)
        {
            var rs = reports.Where(r => types.Contains(r.Type)).ToList();
            int ok = rs.Count(r => r.Status is MStatus.Clean or MStatus.Unported);
            long lt = rs.Sum(r => (long)r.Lines), lok = rs.Where(r => r.Status is MStatus.Clean or MStatus.Unported).Sum(r => (long)r.Lines);
            T += rs.Count; OK += ok; LT += lt; LOK += lok;
            sb.Append($"| `{name}` | {rs.Count} | {ok} | {Pct(ok, rs.Count)} | {lok} / {lt} | {Pct(lok, lt)} | {rs.Count(r => r.Status == MStatus.Failed)} | {rs.Count(r => r.Status == MStatus.NotEmitted)} |\n");
        }
        sb.Append($"| **total** | {T} | {OK} | {Pct(OK, T)} | {LOK} / {LT} | {Pct(LOK, LT)} | | |\n\n");

        sb.Append("## Unsupported constructs, all classes\n\n\"methods\" = methods in which the construct occurs at least once; \"only blocker\" = methods where it is the only kind of refusal (fixing it alone makes them translate).\n\n");
        sb.Append("| construct | occurrences | methods | only blocker | example |\n|---|---:|---:|---:|---|\n");
        var failed = reports.Where(r => r.Status == MStatus.Failed).ToList();
        var occ = failed.SelectMany(r => r.Fails.Select(f => (g: Group(f.kind), f, r))).GroupBy(x => x.g)
            .Select(g => (kind: g.Key, n: g.Count(), methods: g.Select(x => x.r).Distinct().Count(),
                          only: g.Select(x => x.r).Distinct().Count(r => r.Fails.All(f => Group(f.kind) == g.Key)),
                          ex: g.OrderBy(x => x.f.where, StringComparer.Ordinal).First()))
            .OrderByDescending(x => x.methods).ThenBy(x => x.kind, StringComparer.Ordinal).ToList();
        foreach (var o in occ) sb.Append($"| {o.kind} | {o.n} | {o.methods} | {o.only} | `{o.ex.r.Display}` {o.ex.f.where} |\n");

        sb.Append("\n## Library calls with no mapping (top 60 by methods affected)\n\n| library member | occurrences | methods |\n|---|---:|---:|\n");
        var lib = failed.SelectMany(r => r.Fails.Where(f => f.kind.StartsWith("call into an unmapped library") || f.kind.StartsWith("creation of an unmapped library")).Select(f => (d: Detail(f.kind), r)))
            .GroupBy(x => x.d).Select(g => (g.Key, n: g.Count(), m: g.Select(x => x.r).Distinct().Count())).OrderByDescending(x => x.m).ThenBy(x => x.Key, StringComparer.Ordinal).ToList();
        foreach (var l in lib.Take(60)) sb.Append($"| `{l.Key}` | {l.n} | {l.m} |\n");
        sb.Append($"\n{lib.Count} distinct library members in total.\n");

        sb.Append("\n## Value types with no Rust representation (top 30)\n\n| type | occurrences |\n|---|---:|\n");
        var vt = reports.SelectMany(r => r.Fails.Select(f => f.kind).Append(r.NotEmittedReason ?? "")).Where(k => k.Contains("no Rust representation")).Select(k => Detail(k) ?? Regex.Replace(k, "^.*: ", ""))
            .GroupBy(x => x).OrderByDescending(g => g.Count()).ThenBy(g => g.Key, StringComparer.Ordinal).Take(30);
        foreach (var g in vt) sb.Append($"| `{g.Key}` | {g.Count()} |\n");

        sb.Append("\n## Members with no Rust signature\n\n| reason | members |\n|---|---:|\n");
        foreach (var g in reports.Where(r => r.Status == MStatus.NotEmitted).GroupBy(r => Group(r.NotEmittedReason)).OrderByDescending(g => g.Count()))
            sb.Append($"| {g.Key} | {g.Count()} |\n");

        sb.Append("\n## Per class: top unsupported constructs\n");
        foreach (var (name, types) in perType)
        {
            var rs = failed.Where(r => types.Contains(r.Type)).ToList();
            sb.Append($"\n### `{name}`\n\n| construct | methods | example |\n|---|---:|---|\n");
            foreach (var g in rs.SelectMany(r => r.Fails.Select(f => (g: Group(f.kind), f, r))).GroupBy(x => x.g)
                .Select(g => (g.Key, m: g.Select(x => x.r).Distinct().Count(), ex: g.OrderBy(x => x.f.where, StringComparer.Ordinal).First())).OrderByDescending(x => x.m).ThenBy(x => x.Key, StringComparer.Ordinal).Take(12))
                sb.Append($"| {g.Key} | {g.m} | `{g.ex.r.Display}` {g.ex.f.where} |\n");
        }
        var tail = Path.Combine(cfg.BaseDir, "coverage_tail.md");
        if (File.Exists(tail)) sb.Append('\n').Append(File.ReadAllText(tail));
        if (coverage != null) File.WriteAllBytes(coverage, new UTF8Encoding(false).GetBytes(sb.ToString().Replace("\r\n", "\n")));
        Console.WriteLine($"dry run: {T} methods, {OK} translatable ({Pct(OK, T)}), lines {LOK}/{LT} ({Pct(LOK, LT)}) in {sw.ElapsedMilliseconds} ms");
        return 0;
    }

    /// Work item "scale": every type the sources declare, grouped by namespace.
    static int RunAll(Config cfg, CSharpCompilation comp, string coverage, int errorCount, Stopwatch sw)
    {
        var model = new Model(cfg, comp, true);
        var gen = new Gen(model);
        var types = new List<TType>();
        void Walk(INamespaceOrTypeSymbol s)
        {
            foreach (var m in s.GetMembers())
            {
                if (m is INamespaceSymbol ns) Walk(ns);
                else if (m is INamedTypeSymbol t && t.Locations.Any(l => l.IsInSource) && !t.IsImplicitlyDeclared)
                {
                    if (t.TypeKind is TypeKind.Class or TypeKind.Struct) { var tt = model.Get(t); if (tt != null) { model.Pop(tt); types.Add(tt); } }
                    Walk(t);
                }
            }
        }
        Walk(comp.Assembly.GlobalNamespace);
        var work = types.SelectMany(t => t.Methods.Select(m => (t, m))).ToList();
        Program.ParallelBig(Enumerable.Range(0, work.Count).ToList(), Program.Dop, k => gen.Analyse(work[k].t, work[k].m));
        var reports = gen.Reports.ToList();
        static string Ns(TType t) => t.Sym.ContainingNamespace == null || t.Sym.ContainingNamespace.IsGlobalNamespace ? "(global)" : t.Sym.ContainingNamespace.ToDisplayString();
        static int Cat(MethodReport r) => r.Status == MStatus.Failed || r.Status == MStatus.NotEmitted ? 3 : r.Unported.Count > 0 ? 2 : r.HostCalls.Count > 0 ? 1 : 0;
        var sb = new StringBuilder("# cs2rs coverage: the whole decompile (dry run)\n\n");
        sb.Append("Generated by `sh coverage.sh` (`cs2rs --all --coverage COVERAGE.md`). Do not edit by hand; the section \"What is tested\" at the end is appended from `coverage_tail.md`.\n\n");
        sb.Append("Every method, accessor, operator and constructor of every class and struct declared in `decompile/Terraria` is fed through the emitter with every declared type treated as translated. ");
        sb.Append("Columns: **clean** = a body with nothing missing; **host calls** = translated, calls at least one library member through the host boundary (`HOST_API.md`), nothing else missing; ");
        sb.Append("**unported inside** = translated, but reaches a game member that has no Rust function (generic game class, extern, unrepresentable signature); ");
        sb.Append("**refused** = the emitter met a construct it does not support (the body would be `rt::unported_method`) or the member has no Rust signature. ");
        sb.Append("A dry run does not compile or run anything: what rustc accepted and what was compared with the real game is in `SCALE_REPORT.md` and in \"What is tested\" below. ");
        sb.Append("Static initialisers and field initialisers are not counted here (they are bodies in `SCALE_REPORT.md`).\n\n");
        if (errorCount >= 0) sb.Append($"Roslyn compilation of the decompile: {errorCount} errors.\n\n");
        sb.Append("| namespace | types | methods | clean | host calls | unported inside | refused | lines translatable |\n|---|---:|---:|---:|---:|---:|---:|---:|\n");
        int[] tot = new int[4]; int T = 0, TY = 0; long LT = 0, LOK = 0;
        foreach (var g in reports.GroupBy(r => Ns(r.Type)).OrderBy(g => g.Key, StringComparer.Ordinal))
        {
            var c = new int[4];
            foreach (var r in g) c[Cat(r)]++;
            long lt = g.Sum(r => (long)r.Lines), lok = g.Where(r => Cat(r) != 3).Sum(r => (long)r.Lines);
            int ty = g.Select(r => r.Type).Distinct().Count();
            sb.Append($"| `{g.Key}` | {ty} | {g.Count()} | {c[0]} | {c[1]} | {c[2]} | {c[3]} | {Pct(lok, lt)} |\n");
            for (int i = 0; i < 4; i++) tot[i] += c[i];
            T += g.Count(); TY += ty; LT += lt; LOK += lok;
        }
        sb.Append($"| **total** | {TY} | {T} | {tot[0]} | {tot[1]} | {tot[2]} | {tot[3]} | {Pct(LOK, LT)} ({LOK} / {LT}) |\n\n");
        sb.Append($"Translatable (clean + host calls + unported inside): **{tot[0] + tot[1] + tot[2]} of {T} ({Pct(tot[0] + tot[1] + tot[2], T)})**.\n\n");

        sb.Append("## Refusal histogram\n\n\"methods\" = methods in which the construct occurs at least once; \"only blocker\" = methods where it is the only kind of refusal.\n\n");
        sb.Append("| construct | occurrences | methods | only blocker | example |\n|---|---:|---:|---:|---|\n");
        var failed = reports.Where(r => r.Status == MStatus.Failed).ToList();
        var occ = failed.SelectMany(r => r.Fails.Select(f => (g: Group(f.kind), f, r))).GroupBy(x => x.g)
            .Select(g => (kind: g.Key, n: g.Count(), methods: g.Select(x => x.r).Distinct().Count(),
                          only: g.Select(x => x.r).Distinct().Count(r => r.Fails.All(f => Group(f.kind) == g.Key)),
                          ex: g.OrderBy(x => x.f.where, StringComparer.Ordinal).First()))
            .OrderByDescending(x => x.methods).ThenBy(x => x.kind, StringComparer.Ordinal).ToList();
        foreach (var o in occ) sb.Append($"| {o.kind} | {o.n} | {o.methods} | {o.only} | `{o.ex.r.Display}` {o.ex.f.where} |\n");
        sb.Append("\n## Members with no Rust signature\n\n| reason | members |\n|---|---:|\n");
        foreach (var g in reports.Where(r => r.Status == MStatus.NotEmitted).GroupBy(r => Group(r.NotEmittedReason)).OrderByDescending(g => g.Count()))
            sb.Append($"| {g.Key} | {g.Count()} |\n");
        sb.Append("\n## Types with no Rust representation (top 30)\n\n| type | occurrences |\n|---|---:|\n");
        var vt = reports.SelectMany(r => r.Fails.Select(f => f.kind).Append(r.NotEmittedReason ?? "")).Where(k => k.Contains("no Rust representation")).Select(k => Detail(k) ?? Regex.Replace(k, "^.*: ", ""))
            .GroupBy(x => x).OrderByDescending(g => g.Count()).ThenBy(g => g.Key, StringComparer.Ordinal).Take(30);
        foreach (var g in vt) sb.Append($"| `{g.Key}` | {g.Count()} |\n");
        sb.Append("\n## Largest refused methods (source lines)\n\n| method | lines | first refusal |\n|---|---:|---|\n");
        foreach (var r in failed.OrderByDescending(r => r.Lines).ThenBy(r => r.Display, StringComparer.Ordinal).Take(40))
            sb.Append($"| `{r.Display}` | {r.Lines} | {r.Fails[0].kind} ({r.Fails[0].where}) |\n");
        var tail = Path.Combine(cfg.BaseDir, "coverage_tail.md");
        if (File.Exists(tail)) sb.Append('\n').Append(File.ReadAllText(tail));
        if (coverage != null) File.WriteAllBytes(coverage, new UTF8Encoding(false).GetBytes(sb.ToString().Replace("\r\n", "\n")));
        Console.WriteLine($"dry run (all): {TY} types, {T} methods: clean {tot[0]}, host calls {tot[1]}, unported inside {tot[2]}, refused {tot[3]}; lines {LOK}/{LT} ({Pct(LOK, LT)}) in {sw.ElapsedMilliseconds} ms");
        return 0;
    }

    static string Pct(long a, long b) => b == 0 ? "-" : (100.0 * a / b).ToString("0.0", System.Globalization.CultureInfo.InvariantCulture) + "%";
}
