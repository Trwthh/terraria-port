#!/usr/bin/env python3
"""Writes tools/refdump_worldgen/ExtProbesGen.cs from probes.py (the NEW set) plus the hand-written XNA probes below."""
import os
from dsl import emit_cs, HELPERS_CS
from probes import NEW

XNA = r'''
    // ---- real XNA members (Microsoft.Xna.Framework.dll of the game); candidates for each are in float_model/score.py
    static Vector2 SV;
    [MethodImpl(MethodImplOptions.NoInlining)] public static float Q_V01_distance(float x, float y, float z, int n) { return Vector2.Distance(new Vector2(x, y), new Vector2(z, x)); }
    [MethodImpl(MethodImplOptions.NoInlining)] public static float Q_V02_dot(float x, float y, float z, int n) { return Vector2.Dot(new Vector2(x, y), new Vector2(z, x)) + z; }
    [MethodImpl(MethodImplOptions.NoInlining)] public static float Q_V03_scale_length(float x, float y, float z, int n) { return (new Vector2(x, y) * z).Length(); }
    [MethodImpl(MethodImplOptions.NoInlining)] public static float Q_V04_static_vector_field(float x, float y, float z, int n) { SV = new Vector2(x, y); SV += new Vector2(z, x) * 0.5f; return SV.X + SV.Y; }
    [MethodImpl(MethodImplOptions.NoInlining)] public static float Q_V05_lerp(float x, float y, float z, int n) { return MathHelper.Lerp(x, y, z) - x; }
    [MethodImpl(MethodImplOptions.NoInlining)] public static float Q_V06_clamp(float x, float y, float z, int n) { return MathHelper.Clamp(x * y, z, 10f) + x * y; }
    [MethodImpl(MethodImplOptions.NoInlining)] public static float Q_V07_local_vector_scaled(float x, float y, float z, int n) { Vector2 v = new Vector2(x, y); v *= z; v += new Vector2(y, z); return v.X * 3f + v.Y; }
    // ---- inlining: small helpers WITHOUT NoInlining. Whether each call survives in the machine code is read from probes2_code.bin.
    static int HI(int a) { return a * 3 + 1; }
    static int HF2I(float a) { return (int)(a * 16f); }
    static float HI2F(int a) { return a * 0.5f; }
    static bool HGt(float a, float b) { return a > b; }
    static void HSet(float a) { SF = a * 1.5f; }
    static double HD(double a) { return a * 1.5; }
    static V2 HV(V2 v, float s) { V2 r; r.X = v.X * s; r.Y = v.Y * s; return r; }
    class Obj { public float w; public float W { get { return w; } } public float Half { get { return w * 0.5f; } } public int I { get { return (int)w; } } }
    static Obj O = new Obj();
    [MethodImpl(MethodImplOptions.NoInlining)] public static int Q_I01_int_helper(float x, float y, float z, int n) { return HI(n); }
    [MethodImpl(MethodImplOptions.NoInlining)] public static int Q_I02_float_arg_int_result(float x, float y, float z, int n) { return HF2I(x * y); }
    [MethodImpl(MethodImplOptions.NoInlining)] public static float Q_I03_int_arg_float_result(float x, float y, float z, int n) { return HI2F(n) * x; }
    [MethodImpl(MethodImplOptions.NoInlining)] public static int Q_I04_float_args_bool_result(float x, float y, float z, int n) { return HGt(x * y, z * z) ? 1 : 0; }
    [MethodImpl(MethodImplOptions.NoInlining)] public static float Q_I05_float_arg_void(float x, float y, float z, int n) { HSet(x * y); return SF; }
    [MethodImpl(MethodImplOptions.NoInlining)] public static float Q_I06_double_helper(float x, float y, float z, int n) { return (float)(HD(x * y) + z); }
    [MethodImpl(MethodImplOptions.NoInlining)] public static float Q_I07_struct_helper(float x, float y, float z, int n) { V2 v; v.X = x; v.Y = y; V2 r = HV(v, z); return r.X + r.Y * 2f; }
    [MethodImpl(MethodImplOptions.NoInlining)] public static float Q_I08_property_getters(float x, float y, float z, int n) { O.w = x * y; return O.W * z + O.Half + O.I; }
    [MethodImpl(MethodImplOptions.NoInlining)] public static float Q_V08_length_squared(float x, float y, float z, int n) { Vector2 v = new Vector2(x * y, z); return v.LengthSquared() - x; }
'''
out = ["// GENERATED by tools/refdump_worldgen/float_model/gen_cs.py from float_model/probes.py. Do not edit.",
       "using System;", "using System.Runtime.CompilerServices;", "using Microsoft.Xna.Framework;", "",
       "public struct V2 { public float X, Y; }", "", "public static class FP2", "{", "    // <<<PROBES2",
       "    class Holder { public float F; }", "    static float SF;", "    static int SI;", "    static Holder H = new Holder();", "    static float[] F = new float[4];",
       HELPERS_CS.rstrip("\n")]
for name in sorted(NEW):
    out.append(emit_cs(name, NEW[name]))
out.append(XNA.rstrip("\n"))
out.append("    // >>>PROBES2")
out.append("}")
p = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ExtProbesGen.cs")
open(p, "w", newline="\n", encoding="utf-8").write("\n".join(out) + "\n")
print("wrote", os.path.normpath(p), len(NEW), "generated probes + 16 hand-written probes")
