// XnaStubGen: writes the public surface of a real XNA 4.0 assembly (Microsoft.Xna.Framework.Graphics.dll /
// Microsoft.Xna.Framework.Game.dll) as C# source, every member a stub that throws, so a stand-in assembly with the same
// identity has every type and member the game can bind to. Members implemented by hand (tools\refdump_draw\xna\*.cs)
// carry a marker line `//@impl <key>`; the stub of that key is left out (a marker that matches no member is an error).
// Every stub is preceded by `// key: <key>`, the text to copy into a marker.
//
//   XnaStubGen.exe <real assembly> <out .g.cs> <hand-written dir> [<reference dir for dependencies>]
//
// Reflection-only load; C# 5, .NET Framework 4.
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Reflection;
using System.Text;
using System.Text.RegularExpressions;

static class Gen
{
    static string RefDir;
    static HashSet<string> Impl = new HashSet<string>();
    static HashSet<string> Used = new HashSet<string>();
    static StringBuilder O = new StringBuilder();
    const BindingFlags DF = BindingFlags.DeclaredOnly | BindingFlags.Instance | BindingFlags.Static | BindingFlags.Public | BindingFlags.NonPublic;
    static Assembly Asm;

    static int Main(string[] a)
    {
        if (a[0] == "--pubkey") { File.WriteAllBytes(a[2], AssemblyName.GetAssemblyName(a[1]).GetPublicKey()); return 0; }
        RefDir = a.Length > 3 ? a[3] : Path.GetDirectoryName(a[0]);
        AppDomain.CurrentDomain.ReflectionOnlyAssemblyResolve += (s, e) =>
        {
            string n = new AssemblyName(e.Name).Name;
            string p = Path.Combine(RefDir, n + ".dll");
            if (File.Exists(p)) return Assembly.ReflectionOnlyLoadFrom(p);
            return Assembly.ReflectionOnlyLoad(e.Name);
        };
        foreach (string f in Directory.GetFiles(a[2], "*.cs"))
            foreach (string line in File.ReadAllLines(f))
            {
                Match m = Regex.Match(line, @"^\s*//@impl\s+(.+?)\s*$");
                if (m.Success) Impl.Add(m.Groups[1].Value);
            }
        Asm = Assembly.ReflectionOnlyLoadFrom(a[0]);
        O.AppendLine("// Generated by tools\\refdump_draw\\gen\\XnaStubGen.cs from " + Path.GetFileName(a[0]) + " " + Asm.GetName().Version + ". Do not edit.");
        O.AppendLine("#pragma warning disable 0067, 0108, 0109, 0114, 0169, 0414, 0649, 0659, 0660, 0661, 0618, 0628");
        Type[] all = Asm.GetExportedTypes().Where(t => !t.IsNested).OrderBy(t => t.FullName, StringComparer.Ordinal).ToArray();
        foreach (var g in all.GroupBy(t => t.Namespace))
        {
            O.AppendLine("namespace " + g.Key);
            O.AppendLine("{");
            foreach (Type t in g) EmitType(t, 1);
            O.AppendLine("}");
        }
        var unused = Impl.Where(k => !Used.Contains(k)).ToList();
        foreach (string k in unused) Console.Error.WriteLine("marker matches no member: " + k);
        File.WriteAllText(a[1], O.ToString());
        Console.WriteLine("XnaStubGen: " + all.Length + " top-level types, " + Used.Count + " members implemented by hand, written " + a[1]);
        return unused.Count == 0 ? 0 : 1;
    }

    static string Ind(int n) { return new string(' ', 4 * n); }

    // ------------------------------------------------------------------ type names
    static readonly Dictionary<string, string> Kw = new Dictionary<string, string>
    {
        {"System.Void","void"},{"System.Boolean","bool"},{"System.Byte","byte"},{"System.SByte","sbyte"},{"System.Int16","short"},
        {"System.UInt16","ushort"},{"System.Int32","int"},{"System.UInt32","uint"},{"System.Int64","long"},{"System.UInt64","ulong"},
        {"System.Single","float"},{"System.Double","double"},{"System.Char","char"},{"System.String","string"},{"System.Object","object"},
        {"System.Decimal","decimal"},{"System.IntPtr","global::System.IntPtr"}
    };
    // full = code form (global:: qualified), short = key form
    static string TN(Type t, bool full)
    {
        if (t.IsByRef) return TN(t.GetElementType(), full);
        if (t.IsPointer) return TN(t.GetElementType(), full) + "*";
        if (t.IsArray) return TN(t.GetElementType(), full) + "[" + new string(',', t.GetArrayRank() - 1) + "]";
        if (t.IsGenericParameter) return t.Name;
        string kw;
        if (t.FullName != null && Kw.TryGetValue(t.FullName, out kw)) return full || !kw.StartsWith("global::") ? kw : "IntPtr";
        if (t.IsGenericType && t.GetGenericTypeDefinition().FullName == "System.Nullable`1") return TN(t.GetGenericArguments()[0], full) + "?";
        string name = t.Name;
        int tick = name.IndexOf('`'); if (tick >= 0) name = name.Substring(0, tick);
        string args = "";
        if (t.IsGenericType)
        {
            // arguments of this level only (nested generic types do not occur in XNA)
            args = "<" + string.Join(", ", t.GetGenericArguments().Select(x => TN(x, full))) + ">";
        }
        if (t.IsNested)
        {
            Type outer = t.DeclaringType;
            if (outer.IsGenericTypeDefinition && t.IsGenericType && !t.IsGenericTypeDefinition)
            {
                Type[] ta = t.GetGenericArguments();
                int k = outer.GetGenericArguments().Length;
                outer = outer.MakeGenericType(ta.Take(k).ToArray());
                args = ta.Length > k ? "<" + string.Join(", ", ta.Skip(k).Select(x => TN(x, full))) + ">" : "";
            }
            return TN(outer, full) + "." + name + args;
        }
        if (!full) return name + args;
        return "global::" + t.Namespace + "." + name + args;
    }

    static string ParamList(ParameterInfo[] ps, bool full, bool withNames)
    {
        var parts = new List<string>();
        foreach (ParameterInfo p in ps)
        {
            string mod = "";
            if (p.ParameterType.IsByRef) mod = p.IsOut ? "out " : "ref ";
            else if (p.GetCustomAttributesData().Any(c => c.Constructor.DeclaringType.FullName == "System.ParamArrayAttribute")) mod = full ? "params " : "";
            string s = mod + TN(p.ParameterType, full);
            if (withNames) s += " " + (string.IsNullOrEmpty(p.Name) ? "p" + p.Position : Esc(p.Name));
            parts.Add(s);
        }
        return string.Join(", ", parts);
    }
    static string Esc(string n)
    {
        string[] kws = { "object", "string", "base", "this", "params", "event", "operator", "checked", "fixed", "lock", "in", "out", "ref", "default", "value" };
        return kws.Contains(n) ? "@" + n : n;
    }

    static string TypeKey(Type t) { return TN(t, false); }

    // ------------------------------------------------------------------ types
    static bool Visible(MethodBase m) { return m.IsPublic || m.IsFamily || m.IsFamilyOrAssembly; }
    static string Vis(MethodBase m) { return m.IsPublic ? "public" : "protected"; }

    static void EmitType(Type t, int d)
    {
        string i = Ind(d);
        if (t.IsEnum)
        {
            if (t.GetCustomAttributesData().Any(c => c.Constructor.DeclaringType.FullName == "System.FlagsAttribute")) O.AppendLine(i + "[global::System.Flags]");
            O.AppendLine(i + "public enum " + t.Name + " : " + TN(Enum.GetUnderlyingType(t), true));
            O.AppendLine(i + "{");
            foreach (FieldInfo f in t.GetFields(BindingFlags.Public | BindingFlags.Static))
                O.AppendLine(i + "    " + f.Name + " = " + Convert.ToString(f.GetRawConstantValue(), System.Globalization.CultureInfo.InvariantCulture) + ",");
            O.AppendLine(i + "}");
            return;
        }
        if (typeof(MulticastDelegate).FullName == (t.BaseType == null ? null : t.BaseType.FullName))
        {
            MethodInfo inv = t.GetMethod("Invoke");
            O.AppendLine(i + "public delegate " + TN(inv.ReturnType, true) + " " + t.Name + "(" + ParamList(inv.GetParameters(), true, true) + ");");
            return;
        }
        string kind = t.IsInterface ? "interface" : t.IsValueType ? "struct" : "class";
        string mods = "public ";
        if (!t.IsInterface && !t.IsValueType)
        {
            if (t.IsAbstract && t.IsSealed) mods += "static ";
            else if (t.IsAbstract) mods += "abstract ";
            else if (t.IsSealed) mods += "sealed ";
        }
        var bases = new List<string>();
        if (!t.IsInterface && !t.IsValueType && t.BaseType != null && t.BaseType.FullName != "System.Object") bases.Add(TN(t.BaseType, true));
        Type[] baseIfaces = t.BaseType != null ? t.BaseType.GetInterfaces() : new Type[0];
        foreach (Type it in t.GetInterfaces())
        {
            if (baseIfaces.Contains(it) && !t.IsInterface) continue;
            // only the directly listed ones (not those inherited by another listed interface)
            if (t.GetInterfaces().Any(o => o != it && o.GetInterfaces().Contains(it))) continue;
            if (!it.IsPublic && !it.IsNestedPublic) continue;
            bases.Add(TN(it, true));
        }
        string gen = t.IsGenericTypeDefinition ? "<" + string.Join(", ", t.GetGenericArguments().Select(x => x.Name)) + ">" : "";
        string nm = t.Name; int tick = nm.IndexOf('`'); if (tick >= 0) nm = nm.Substring(0, tick);
        O.AppendLine(i + mods + (t.IsInterface ? "" : "partial ") + kind + " " + nm + gen + (bases.Count > 0 ? " : " + string.Join(", ", bases) : ""));
        O.AppendLine(i + "{");
        string tk = TypeKey(t);
        if (t.IsInterface) EmitInterfaceMembers(t, d + 1);
        else { EmitMembers(t, tk, d + 1); EmitExplicit(t, tk, d + 1); }
        foreach (Type n in t.GetNestedTypes(BindingFlags.Public).OrderBy(x => x.Name, StringComparer.Ordinal)) EmitType(n, d + 1);
        O.AppendLine(i + "}");
    }

    static void EmitInterfaceMembers(Type t, int d)
    {
        string i = Ind(d);
        foreach (PropertyInfo p in t.GetProperties(DF))
        {
            var ps = p.GetIndexParameters();
            string name = ps.Length > 0 ? "this[" + ParamList(ps, true, true) + "]" : p.Name;
            O.AppendLine(i + TN(p.PropertyType, true) + " " + name + " { " + (p.GetGetMethod() != null ? "get; " : "") + (p.GetSetMethod() != null ? "set; " : "") + "}");
        }
        foreach (EventInfo e in t.GetEvents(DF)) O.AppendLine(i + "event " + TN(e.EventHandlerType, true) + " " + e.Name + ";");
        foreach (MethodInfo m in t.GetMethods(DF).Where(m => !m.IsSpecialName))
            O.AppendLine(i + TN(m.ReturnType, true) + " " + m.Name + GenArgs(m) + "(" + ParamList(m.GetParameters(), true, true) + ")" + Constraints(m) + ";");
    }

    static string GenArgs(MethodInfo m) { return m.IsGenericMethodDefinition ? "<" + string.Join(", ", m.GetGenericArguments().Select(x => x.Name)) + ">" : ""; }
    static string Constraints(MethodInfo m)
    {
        if (!m.IsGenericMethodDefinition) return "";
        var sb = new StringBuilder();
        foreach (Type g in m.GetGenericArguments())
        {
            var cs = new List<string>();
            var ga = g.GenericParameterAttributes;
            if ((ga & GenericParameterAttributes.NotNullableValueTypeConstraint) != 0) cs.Add("struct");
            else if ((ga & GenericParameterAttributes.ReferenceTypeConstraint) != 0) cs.Add("class");
            foreach (Type c in g.GetGenericParameterConstraints()) if (c.FullName != "System.ValueType") cs.Add(TN(c, true));
            if ((ga & GenericParameterAttributes.DefaultConstructorConstraint) != 0 && (ga & GenericParameterAttributes.NotNullableValueTypeConstraint) == 0) cs.Add("new()");
            if (cs.Count > 0) sb.Append(" where " + g.Name + " : " + string.Join(", ", cs));
        }
        return sb.ToString();
    }

    static bool Claim(string key)
    {
        if (Impl.Contains(key)) { Used.Add(key); return true; }
        return false;
    }

    static string Throw(string key) { return "{ throw new global::System.NotImplementedException(\"XNA stand-in: " + key.Replace("\"", "'") + "\"); }"; }

    static string MethodMods(MethodInfo m, Type t)
    {
        string s = "";
        if (m.IsStatic) s += "static ";
        else if (m.IsAbstract) s += "abstract ";
        else if (m.IsVirtual && !m.IsFinal)
        {
            bool isOverride = m.GetBaseDefinition().DeclaringType != m.DeclaringType;
            if (isOverride) s += "override ";
            else if ((m.Attributes & MethodAttributes.NewSlot) != 0) s += "virtual ";
            else s += "virtual ";
        }
        else if (m.IsVirtual && m.IsFinal)
        {
            bool isOverride = m.GetBaseDefinition().DeclaringType != m.DeclaringType;
            if (isOverride) s += "sealed override ";
        }
        return s;
    }

    static bool HasPointer(MethodBase m)
    {
        return m.GetParameters().Any(p => p.ParameterType.IsPointer || (p.ParameterType.IsByRef && p.ParameterType.GetElementType().IsPointer))
            || (m is MethodInfo && ((MethodInfo)m).ReturnType.IsPointer);
    }

    static void EmitMembers(Type t, string tk, int d)
    {
        string i = Ind(d);
        bool isStatic = t.IsAbstract && t.IsSealed;
        // fields
        foreach (FieldInfo f in t.GetFields(DF).OrderBy(f => f.MetadataToken))
        {
            if (f.Name.Contains("<")) continue;
            bool vis = f.IsPublic || f.IsFamily || f.IsFamilyOrAssembly;
            // private instance fields of a struct keep its layout
            bool keepPrivate = t.IsValueType && !f.IsStatic;
            if (!vis && !keepPrivate) continue;
            string key = tk + "." + f.Name;
            if (vis && Claim(key)) continue;
            string v = f.IsPublic ? "public" : f.IsFamily || f.IsFamilyOrAssembly ? "protected" : "private";
            string ftn = TN(f.FieldType, true);
            if (!vis) { if (f.FieldType.IsPointer) ftn = "global::System.IntPtr"; else if (!f.FieldType.IsPublic && !f.FieldType.IsNestedPublic && !f.FieldType.IsPrimitive && f.FieldType.Assembly == Asm) ftn = "global::System.IntPtr"; }
            if (vis) O.AppendLine(i + "// key: " + key);
            if (f.IsLiteral)
            {
                O.AppendLine(i + v + " const " + ftn + " " + f.Name + " = " + Lit(f.GetRawConstantValue(), f.FieldType) + ";");
                continue;
            }
            O.AppendLine(i + v + (f.IsStatic ? " static" : "") + (f.IsInitOnly ? " readonly" : "") + " " + ftn + " " + f.Name + ";");
        }
        // the constructor every stub chains to
        if (!t.IsValueType && !isStatic)
        {
            bool baseInGen = t.BaseType != null && t.BaseType.Assembly == Asm;
            string chainBase = "";
            if (baseInGen) chainBase = " : base(_)";
            else if (t.BaseType != null)
            {
                ConstructorInfo bc = t.BaseType.GetConstructors(BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic)
                    .Where(c => c.IsPublic || c.IsFamily || c.IsFamilyOrAssembly).OrderBy(c => c.GetParameters().Length).FirstOrDefault();
                if (bc != null && bc.GetParameters().Length > 0)
                    chainBase = " : base(" + string.Join(", ", bc.GetParameters().Select(p => "default(" + TN(p.ParameterType, true) + ")")) + ")";
            }
            O.AppendLine(i + "internal " + t.Name + "(global::Microsoft.Xna.Framework.XnaStandIn.StubCtor _)" + chainBase + " { }");
        }
        // constructors
        foreach (ConstructorInfo c in t.GetConstructors(DF).Where(c => !c.IsStatic && Visible(c)))
        {
            string key = tk + "..ctor(" + ParamList(c.GetParameters(), false, false) + ")";
            if (Claim(key)) continue;
            O.AppendLine(i + "// key: " + key);
            string chain = t.IsValueType ? (c.GetParameters().Length == 0 ? "" : " : this()") : " : this(default(global::Microsoft.Xna.Framework.XnaStandIn.StubCtor))";
            if (t.IsValueType && c.GetParameters().Length == 0) continue;
            O.AppendLine(i + (HasPointer(c) ? "unsafe " : "") + Vis(c) + " " + t.Name + "(" + ParamList(c.GetParameters(), true, true) + ")" + chain + " " + Throw(key));
        }
        // properties
        foreach (PropertyInfo p in t.GetProperties(DF))
        {
            MethodInfo g = p.GetGetMethod(true), s = p.GetSetMethod(true);
            MethodInfo any = g ?? s;
            bool explicitImpl = false;
            if (!((g != null && Visible(g)) || (s != null && Visible(s)))) continue;
            var ps = p.GetIndexParameters();
            string pname = ps.Length > 0 ? "this[" + ParamList(ps, true, true) + "]" : p.Name;
            string key = tk + "." + (ps.Length > 0 ? "this[" + ParamList(ps, false, false) + "]" : p.Name);
            if (Claim(key)) continue;
            O.AppendLine(i + "// key: " + key);
            if (explicitImpl)
            {
                string iface = p.Name.Substring(0, p.Name.LastIndexOf('.'));
                Type it = t.GetInterfaces().First(x => x.FullName == iface || x.FullName.Replace('+', '.') == iface);
                string pn = p.Name.Substring(p.Name.LastIndexOf('.') + 1);
                O.AppendLine(i + TN(p.PropertyType, true) + " " + TN(it, true) + "." + (ps.Length > 0 ? "this[" + ParamList(ps, true, true) + "]" : pn) + " { " + (g != null ? "get " + Throw(key) + " " : "") + (s != null ? "set " + Throw(key) + " " : "") + "}");
                continue;
            }
            bool gv = g != null && Visible(g), sv = s != null && Visible(s);
            MethodInfo main = gv ? g : s;
            string pv = (gv && g.IsPublic) || (sv && s.IsPublic) ? "public" : "protected";
            string acc = "";
            if (gv) acc += (pv == "public" && !g.IsPublic ? "protected " : "") + (main.IsAbstract ? "get; " : "get " + Throw(key) + " ");
            if (sv) acc += (pv == "public" && !s.IsPublic ? "protected " : "") + (main.IsAbstract ? "set; " : "set " + Throw(key) + " ");
            O.AppendLine(i + pv + " " + MethodMods(main, t) + TN(p.PropertyType, true) + " " + pname + " { " + acc + "}");
        }
        // events
        foreach (EventInfo e in t.GetEvents(DF))
        {
            MethodInfo add = e.GetAddMethod(true);
            if (!Visible(add)) continue;
            string key = tk + "." + e.Name;
            if (Claim(key)) continue;
            O.AppendLine(i + "// key: " + key);
            O.AppendLine(i + Vis(add) + " " + MethodMods(add, t) + "event " + TN(e.EventHandlerType, true) + " " + e.Name + " { add " + Throw(key) + " remove " + Throw(key) + " }");
        }
        // methods
        foreach (MethodInfo m in t.GetMethods(DF))
        {
            if (m.IsSpecialName && !m.Name.StartsWith("op_")) continue;
            bool explicitImpl = false;
            if (!Visible(m)) continue;
            if (m.Name == "Finalize") continue;
            string ps = ParamList(m.GetParameters(), false, false);
            string key = tk + "." + m.Name + GenArgs(m) + "(" + ps + ")";
            if (Claim(key)) continue;
            O.AppendLine(i + "// key: " + key);
            string unsafeMod = HasPointer(m) ? "unsafe " : "";
            if (explicitImpl)
            {
                string iface = m.Name.Substring(0, m.Name.LastIndexOf('.'));
                Type it = t.GetInterfaces().First(x => x.FullName == iface || x.FullName.Replace('+', '.') == iface);
                O.AppendLine(i + unsafeMod + TN(m.ReturnType, true) + " " + TN(it, true) + "." + m.Name.Substring(m.Name.LastIndexOf('.') + 1) + GenArgs(m) + "(" + ParamList(m.GetParameters(), true, true) + ") " + Throw(key));
                continue;
            }
            if (m.Name.StartsWith("op_"))
            {

                if (m.Name == "op_Implicit" || m.Name == "op_Explicit")
                    O.AppendLine(i + "public static " + (m.Name == "op_Implicit" ? "implicit" : "explicit") + " operator " + TN(m.ReturnType, true) + "(" + ParamList(m.GetParameters(), true, true) + ") " + Throw(key));
                else
                    O.AppendLine(i + "public static " + TN(m.ReturnType, true) + " operator " + OpName(m.Name) + "(" + ParamList(m.GetParameters(), true, true) + ") " + Throw(key));
                continue;
            }
            string body = m.IsAbstract ? ";" : " " + Throw(key);
            O.AppendLine(i + unsafeMod + Vis(m) + " " + MethodMods(m, t) + TN(m.ReturnType, true) + " " + m.Name + GenArgs(m) + "(" + ParamList(m.GetParameters(), true, true) + ")" + (m.IsVirtual && m.GetBaseDefinition().DeclaringType != m.DeclaringType ? "" : Constraints(m)) + body);
        }
    }

    // interface members implemented by a non-public method of t: explicit implementations
    static void EmitExplicit(Type t, string tk, int d)
    {
        string i = Ind(d);
        foreach (Type it in t.GetInterfaces())
        {
            if (!it.IsPublic && !it.IsNestedPublic) continue;
            InterfaceMapping map = t.GetInterfaceMap(it);
            for (int k = 0; k < map.TargetMethods.Length; k++)
            {
                MethodInfo target = map.TargetMethods[k], im = map.InterfaceMethods[k];
                if (target.DeclaringType != t || Visible(target)) continue;
                string itn = TN(it, true);
                string key = tk + "." + TN(it, false) + "." + im.Name + "(" + ParamList(im.GetParameters(), false, false) + ")";
                if (Claim(key)) continue;
                O.AppendLine(i + "// key: " + key);
                if (im.IsSpecialName && (im.Name.StartsWith("get_") || im.Name.StartsWith("set_")))
                {
                    string pn = im.Name.Substring(4);
                    PropertyInfo ip = it.GetProperty(pn);
                    var ips = ip.GetIndexParameters();
                    // one accessor per declaration is not allowed: emit the property once, at its getter (or setter if none)
                    if (im.Name.StartsWith("set_") && ip.GetGetMethod() != null) continue;
                    O.AppendLine(i + TN(ip.PropertyType, true) + " " + itn + "." + (ips.Length > 0 ? "this[" + ParamList(ips, true, true) + "]" : pn) + " { " + (ip.GetGetMethod() != null ? "get " + Throw(key) + " " : "") + (ip.GetSetMethod() != null ? "set " + Throw(key) + " " : "") + "}");
                    continue;
                }
                if (im.IsSpecialName && (im.Name.StartsWith("add_") || im.Name.StartsWith("remove_")))
                {
                    if (im.Name.StartsWith("remove_")) continue;
                    EventInfo ie = it.GetEvent(im.Name.Substring(4));
                    O.AppendLine(i + "event " + TN(ie.EventHandlerType, true) + " " + itn + "." + ie.Name + " { add " + Throw(key) + " remove " + Throw(key) + " }");
                    continue;
                }
                O.AppendLine(i + TN(im.ReturnType, true) + " " + itn + "." + im.Name + GenArgs(im) + "(" + ParamList(im.GetParameters(), true, true) + ") " + Throw(key));
            }
        }
    }

    static string OpName(string n)
    {
        switch (n)
        {
            case "op_Equality": return "==";
            case "op_Inequality": return "!=";
            case "op_Addition": return "+";
            case "op_Subtraction": return "-";
            case "op_Multiply": return "*";
            case "op_Division": return "/";
            case "op_UnaryNegation": return "-";
            default: throw new Exception("operator " + n);
        }
    }

    static string Lit(object v, Type t)
    {
        if (v == null) return "null";
        if (v is string) return "\"" + ((string)v).Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
        if (v is bool) return (bool)v ? "true" : "false";
        if (v is float) return ((float)v).ToString("R", System.Globalization.CultureInfo.InvariantCulture) + "f";
        if (v is double) return ((double)v).ToString("R", System.Globalization.CultureInfo.InvariantCulture);
        if (t.IsEnum) return "(" + TN(t, true) + ")" + Convert.ToString(v, System.Globalization.CultureInfo.InvariantCulture);
        return "(" + TN(t, true) + ")" + Convert.ToString(v, System.Globalization.CultureInfo.InvariantCulture);
    }
}
