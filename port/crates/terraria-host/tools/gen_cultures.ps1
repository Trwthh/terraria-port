# Generates src\sys\cultures.rs: the .NET Framework DateTimeFormat data of the cultures the game supports
# (Terraria.Localization.GameCulture: en-US de-DE it-IT fr-FR es-ES ru-RU zh-Hans pt-BR pl-PL ja-JP ko-KR zh-Hant)
# plus the invariant culture, read from the real CultureInfo of this machine's .NET Framework 4.
# Usage (from the crate folder): powershell -NoProfile -ExecutionPolicy Bypass -File tools\gen_cultures.ps1
$ErrorActionPreference = 'Stop'
$names = 'en-US', 'de-DE', 'it-IT', 'fr-FR', 'es-ES', 'ru-RU', 'zh-Hans', 'pt-BR', 'pl-PL', 'ja-JP', 'ko-KR', 'zh-Hant'
function Q($s) {
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.Append('"')
    foreach ($c in $s.ToCharArray()) {
        $n = [int]$c
        if ($c -eq '"') { [void]$sb.Append('\"') }
        elseif ($c -eq '\') { [void]$sb.Append('\\') }
        elseif ($n -ge 32 -and $n -lt 127) { [void]$sb.Append($c) }
        else { [void]$sb.Append([string][char]92 + 'u{' + $n.ToString('x') + '}') }
    }
    [void]$sb.Append('"')
    $sb.ToString()
}
function Arr($a) { '[' + (($a | ForEach-Object { Q $_ }) -join ', ') + ']' }
$out = New-Object System.Collections.Generic.List[string]
$out.Add('//! Generated by tools/gen_cultures.ps1 from the .NET Framework CultureInfo data of the cultures the game supports. Do not edit.')
$out.Add('')
$out.Add('pub struct Culture {')
$out.Add('    pub name: &''static str,')
$out.Add('    pub display_name: &''static str,')
$out.Add('    pub long_date: &''static str,')
$out.Add('    pub short_date: &''static str,')
$out.Add('    pub month_names: [&''static str; 12],')
$out.Add('    pub month_genitive: [&''static str; 12],')
$out.Add('    pub month_abbr: [&''static str; 12],')
$out.Add('    pub day_names: [&''static str; 7],')
$out.Add('    pub day_abbr: [&''static str; 7],')
$out.Add('    pub date_separator: &''static str,')
$out.Add('    pub time_separator: &''static str,')
$out.Add('    pub am: &''static str,')
$out.Add('    pub pm: &''static str,')
$out.Add('}')
$out.Add('')
$out.Add('pub static CULTURES: &[Culture] = &[')
foreach ($n in (@('') + $names)) {
    $c = [Globalization.CultureInfo]::GetCultureInfo($n)
    $f = $c.DateTimeFormat
    $label = if ($n -eq '') { '' } else { $n }
    $out.Add('    Culture {')
    $out.Add("        name: $(Q $label),")
    $out.Add("        display_name: $(Q $c.DisplayName),")
    $out.Add("        long_date: $(Q $f.LongDatePattern),")
    $out.Add("        short_date: $(Q $f.ShortDatePattern),")
    $out.Add("        month_names: $(Arr $f.MonthNames[0..11]),")
    $out.Add("        month_genitive: $(Arr $f.MonthGenitiveNames[0..11]),")
    $out.Add("        month_abbr: $(Arr $f.AbbreviatedMonthNames[0..11]),")
    $out.Add("        day_names: $(Arr $f.DayNames),")
    $out.Add("        day_abbr: $(Arr $f.AbbreviatedDayNames),")
    $out.Add("        date_separator: $(Q $f.DateSeparator),")
    $out.Add("        time_separator: $(Q $f.TimeSeparator),")
    $out.Add("        am: $(Q $f.AMDesignator),")
    $out.Add("        pm: $(Q $f.PMDesignator),")
    $out.Add('    },')
}
$out.Add('];')
[IO.File]::WriteAllText((Join-Path $PSScriptRoot '..\src\sys\cultures.rs'), (($out -join "`n") + "`n"), (New-Object System.Text.UTF8Encoding($false)))
"cultures: $($names.Count + 1)"
