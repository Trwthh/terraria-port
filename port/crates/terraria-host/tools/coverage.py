STATUS = {"T": "implemented + tested", "U": "implemented, untested", "O": "object model only", "X": "unimplemented"}


def read_host_api():
    rows = []
    namespace = None
    for line in open(HOST_API, encoding="utf-8"):
        m = re.match(r"## `(.+)`", line)
        if m:
            namespace = m.group(1)
        if not line.startswith("| `") or namespace is None:
            continue
        c = [x.strip() for x in line.strip().strip("|").split(" | ")]
        if len(c) < 6:
            continue
        m = re.match(r"`(.+?)`(?: \(`(get|set)`\))?$", c[1])
        if not m:
            continue
        rows.append({"member": c[0].strip("`"), "key": m.group(1), "accessor": m.group(2) or "", "sites": int(c[4]), "namespace": namespace})
    return rows


def main():
    table = {}
    for key, area, status, text in R:
        k = expand(key)
        if k in table:
            sys.exit(f"duplicate rule {k}")
        table[k] = (area, status, expand(text))

    def lookup(key, accessor):
        for k in ([f"{key}/{accessor}"] if accessor else []) + [key]:
            if k in table:
                return k, table[k]
        return None, None

    rows = read_host_api()
    used = set()
    for r in rows:
        k, rule = lookup(r["key"], r["accessor"])
        r["rule"] = rule
        if k:
            used.add(k)

    # ---- native.d/host_<area>.json
    os.makedirs(NATIVE_D, exist_ok=True)
    areas = sorted({a for _, a, _, _, _ in TYPES} | {v[0] for v in table.values()})
    for area in areas:
        types = {expand(t): ({"rust": expand(rust), "kind": kind} | ({"is": expand(is_)} if is_ else {})) for t, a, rust, kind, is_ in TYPES if a == area}
        members = {}
        for k, (a, status, text) in table.items():
            if a != area or status == "X":
                continue
            base, _, accessor = k.partition("/")
            if accessor:
                members.setdefault(base, {})[accessor] = text
            else:
                members[base] = text
        path = os.path.join(NATIVE_D, f"host_{area}.json")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(f"// Generated by port/crates/terraria-host/tools/coverage.py from its RULES table. Do not edit: edit the rule.\n")
            f.write(f"// Owner: the host worker. Rust side: port\\crates\\terraria-host. Status per member: port\\crates\\terraria-host\\COVERAGE.md.\n")
            for note in AREA_NOTES.get(area, []):
                f.write(f"// NOTE: {note}\n")
            json.dump({"nativeTypes": types, "nativeMembers": members}, f, indent=2)
            f.write("\n")

    if "--install" in sys.argv:
        import shutil
        for area in areas:
            shutil.copyfile(os.path.join(NATIVE_D, f"host_{area}.json"), os.path.join(INSTALL_D, f"host_{area}.json"))
        print(f"installed {len(areas)} tables into {INSTALL_D}")

    # ---- COVERAGE.md
    out = []
    total = len(rows)
    sites = sum(r["sites"] for r in rows)
    out.append("# terraria-host coverage of HOST_API.md\n")
    out.append("Generated by `tools/coverage.py` from `tools\\cs2rs\\HOST_API.md` and the script's RULES table. Do not edit.\n")
    out.append(f"HOST_API.md lists **{total}** members with **{sites}** call sites. Status of each, as this crate sees it:\n")
    out.append("- **implemented + tested**: a Rust implementation with a unit test in this crate (expected values from decompiled XNA or from real .NET Framework: `tests/dotnet/*.ps1`).")
    out.append("- **implemented, untested**: implemented; no unit test of its own (thin accessors, or behaviour only seen through `host_demo`).")
    out.append("- **object model only**: the object exists and keeps state; the effect is not produced (effects are not executed, depth / stencil is not replayed, XACT cues make no sound, no process is started).")
    out.append("- **unimplemented**: stays a registry call (`host::unimplemented` / `unimplemented_value`). The reason says whose gap it is: `host` (this crate), `relogic` (ReLogic code that cs2rs translates), `runtime` (needs the cs2rs runtime / generator).\n")
    out.append("**The mapping tables (`native.d/host_*.json` in this crate; `tools/coverage.py --install` copies them to `tools/cs2rs/native.d`) have NOT been compiled inside `terraria-gen`.** 'Tested' is about the Rust behaviour, not about a template's text.\n")

    def count(rs):
        c = {s: [0, 0] for s in "TUOX"}
        for r in rs:
            s = r["rule"][1] if r["rule"] else "X"
            c[s][0] += 1
            c[s][1] += r["sites"]
        return c

    def row(label, rs):
        c = count(rs)
        n = len(rs)
        s = sum(r["sites"] for r in rs)
        cells = " | ".join(f"{c[k][0]} / {c[k][1]}" for k in "TUOX")
        return f"| {label} | {n} / {s} | {cells} |"

    out.append("## Summary (members / call sites)\n")
    out.append("| | total | implemented + tested | implemented, untested | object model only | unimplemented |")
    out.append("|---|---:|---:|---:|---:|---:|")
    out.append(row("**all**", rows))
    for ns in sorted({r["namespace"] for r in rows}):
        out.append(row(f"`{ns}`", [r for r in rows if r["namespace"] == ns]))
    out.append("")
    unimpl = [r for r in rows if not r["rule"] or r["rule"][1] == "X"]
    by_owner = {}
    for r in unimpl:
        owner = (r["rule"][2].split(":")[0] if r["rule"] else "no rule")
        by_owner.setdefault(owner, []).append(r)
    out.append("Unimplemented by owner:\n")
    out.append("| owner | members | call sites |")
    out.append("|---|---:|---:|")
    for owner, rs in sorted(by_owner.items()):
        out.append(f"| {owner} | {len(rs)} | {sum(r['sites'] for r in rs)} |")
    out.append("")

    for ns in sorted({r["namespace"] for r in rows}):
        out.append(f"## `{ns}`\n")
        out.append("| member | status | call sites | Rust / reason |")
        out.append("|---|---|---:|---|")
        for r in [r for r in rows if r["namespace"] == ns]:
            if r["rule"]:
                _, status, text = r["rule"]
                detail = f"`{text}`" if status != "X" else text
            else:
                status, detail = "X", "host: no rule in tools/coverage.py yet (new in HOST_API.md)"
            out.append(f"| `{r['member']}` | {STATUS[status]} | {r['sites']} | {detail.replace('|', chr(92) + '|')} |")
        out.append("")

    extra = sorted(k for k in table if k not in used and table[k][1] != "X")
    out.append("## Implemented ahead of HOST_API.md\n")
    out.append(f"{len(extra)} members this crate implements and maps that the translated code does not call yet (they are in `native.d\\host_*.json`; the keys were written by hand from the XNA / .NET signatures and are unchecked until a call site makes them appear in HOST_API.md):\n")
    out.append("| key | status | Rust |")
    out.append("|---|---|---|")
    for k in extra:
        out.append(f"| `{k}` | {STATUS[table[k][1]]} | `{table[k][2].replace('|', chr(92) + '|')}` |")
    stale = sorted(k for k in table if k not in used and table[k][1] == "X")
    if stale:
        out.append("\nRules marked unimplemented that match no HOST_API.md row any more (the member was mapped elsewhere or is no longer called):\n")
        for k in stale:
            out.append(f"- `{k}`")
    with open(os.path.join(CRATE, "COVERAGE.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")

    c = count(rows)
    print(f"HOST_API: {total} members / {sites} sites")
    for k in "TUOX":
        print(f"  {STATUS[k]:24} {c[k][0]:4} members {c[k][1]:5} sites")
    print(f"  rules without a HOST_API row: {len(extra)} implemented, {len(stale)} unimplemented")
    norule = [r for r in rows if not r["rule"]]
    for r in norule:
        print("  NO RULE:", r["key"], r["accessor"])


if __name__ == "__main__":
    main()
