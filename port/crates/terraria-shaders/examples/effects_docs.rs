//! Regenerates `port/crates/terraria-host/docs/effects`: the full listing of the game's three compiled effects
//! (`<Effect>.md`), the assembly of every pass (`asm/`), the generated WGSL (`wgsl/`) and `COVERAGE.md` (opcode
//! histogram, pass table with the results of the interpreter-versus-GPU test).
//!
//! From `port/`: `CARGO_TARGET_DIR=target-host cargo run -p terraria-shaders --example effects_docs`
//! Deterministic: running it twice writes identical files. `verification.tsv` is written by the test
//! `gpu_vs_interpreter` (run that first to refresh the verification columns).

#[path = "../tests/support/mod.rs"]
mod support;

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use support::{Loaded, Pass};
use terraria_host::gfx::fx_binary::{FxAnnotation, FxPass, FxState, FxStateSource, FxValue, StateClass};
use terraria_shaders::bytecode::{Opcode, Shader};
use terraria_shaders::{check, disasm, wgsl};

fn write(path: &Path, text: &str) {
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, text.replace("\r\n", "\n")).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
}

fn annotations(list: &[FxAnnotation]) -> String {
    if list.is_empty() {
        return "none".into();
    }
    list.iter()
        .map(|a| match (&a.text, &a.value) {
            (Some(t), _) => format!("{} {} = \"{t}\"", a.ty.hlsl(), a.ty.name),
            (None, FxValue::Numeric(raw)) => format!("{} {} = {:?}", a.ty.hlsl(), a.ty.name, raw),
            _ => format!("{} {}", a.ty.hlsl(), a.ty.name),
        })
        .collect::<Vec<_>>()
        .join("; ")
}

fn state_text(s: &FxState) -> String {
    let index = if s.index != 0 { format!("[{}]", s.index) } else { String::new() };
    match &s.source {
        FxStateSource::Shader(b) => format!("{}{index} = compiled shader ({} bytes)", s.name(), b.len()),
        FxStateSource::Constant => format!("{}{index} = {:?}", s.name(), s.value),
        FxStateSource::Expression(b) => format!("{}{index} = expression ({} bytes)", s.name(), b.len()),
        FxStateSource::Parameter(p) => format!("{}{index} = <{p}>", s.name()),
        FxStateSource::ArraySelector { parameter, .. } => format!("{}{index} = <{parameter}>[expression]", s.name()),
    }
}

fn constants_text(s: &Shader) -> (String, String) {
    let Some(t) = &s.ctab else { return ("none".into(), "none".into()) };
    let floats: Vec<String> = t.floats().map(|c| format!("`{}` {} {}", c.registers(), c.hlsl(), c.name)).collect();
    let samplers: Vec<String> = t.samplers().map(|c| format!("`{}` {}", c.registers(), c.name)).collect();
    (if floats.is_empty() { "none".into() } else { floats.join(", ") }, if samplers.is_empty() { "none".into() } else { samplers.join(", ") })
}

fn count_ops(s: &Shader, ops: &mut BTreeMap<&'static str, usize>) {
    for i in &s.instructions {
        let name = match (i.opcode, i.control) {
            (Opcode::TexLd, 1) => "texldp",
            (Opcode::TexLd, 2) => "texldb",
            (o, _) => o.name(),
        };
        *ops.entry(name).or_default() += 1;
    }
}

fn effect_listing(e: &Loaded) -> String {
    let fx_pass = |p: &Pass| -> &FxPass { &e.fx.techniques.iter().find(|t| t.name == p.technique).expect("technique").passes[p.index] };
    let mut out = String::new();
    let _ = writeln!(out, "# {}\n", e.name);
    let _ = writeln!(out, "Generated by `cargo run -p terraria-shaders --example effects_docs` from `Content/{}.xnb` of the player's install. Do not edit.\n", e.name);
    let _ = writeln!(out, "Compiled D3DX effect: {} bytes, {} parameters, {} techniques, {} passes, {} objects, header shader count {}.\n", e.file_size, e.fx.parameters.len(), e.fx.techniques.len(), e.passes.len(), e.fx.objects.len(), e.fx.shader_count);

    let _ = writeln!(out, "## Parameters\n");
    let _ = writeln!(out, "| # | name | type | semantic | default in the file | annotations | flags |");
    let _ = writeln!(out, "|---|---|---|---|---|---|---|");
    for (i, p) in e.fx.parameters.iter().enumerate() {
        let semantic = if p.ty.semantic.is_empty() { "-" } else { &p.ty.semantic };
        let _ = writeln!(out, "| {i} | `{}` | {} | {semantic} | {} | {} | {} |", p.name(), p.ty.hlsl(), support::default_text(p), annotations(&p.annotations), p.flags);
    }
    let strings: Vec<String> = e.fx.objects.iter().enumerate().filter(|(_, o)| !o.is_empty()).map(|(i, o)| format!("{i}: {:?}", String::from_utf8_lossy(o))).collect();
    let _ = writeln!(out, "\nSmall objects (strings, texture names): {}.\n", if strings.is_empty() { "none".to_owned() } else { strings.join(", ") });

    for t in &e.fx.techniques {
        let _ = writeln!(out, "## Technique `{}` ({} passes; annotations: {})\n", t.name, t.passes.len(), annotations(&t.annotations));
        let _ = writeln!(out, "| # | pass | pixel shader | preshader | vertex shader | samplers | other state assignments |");
        let _ = writeln!(out, "|---|---|---|---|---|---|---|");
        for p in e.passes.iter().filter(|p| p.technique == t.name) {
            let fp = fx_pass(p);
            let pre = p.pixel.preshader.as_ref().map_or("-".to_owned(), |x| format!("{} instr.", x.instructions.len()));
            let vs = p.vertex.as_ref().map_or("- (SpriteBatch's)".to_owned(), |v| format!("{}, {} instr.", v.model(), v.executable().count()));
            let other: Vec<String> = fp.states.iter().filter(|s| !matches!(s.class(), StateClass::PixelShader | StateClass::VertexShader)).map(state_text).collect();
            let _ = writeln!(
                out,
                "| {} | [`{}`](#{}-{}) | {}, {} instr. | {pre} | {vs} | {} | {} |",
                p.index,
                p.name,
                p.index,
                p.name.to_lowercase(),
                p.pixel.model(),
                p.pixel.executable().count(),
                constants_text(&p.pixel).1,
                if other.is_empty() { "none".to_owned() } else { other.join("; ") }
            );
        }
        let _ = writeln!(out);
        for p in e.passes.iter().filter(|p| p.technique == t.name) {
            let fp = fx_pass(p);
            let _ = writeln!(out, "### {} {}\n", p.index, p.name);
            let _ = writeln!(out, "- files: [assembly](asm/{}.asm), [WGSL](wgsl/{}.wgsl)", p.stem(), p.stem());
            let _ = writeln!(out, "- annotations: {}", annotations(&fp.annotations));
            let _ = writeln!(out, "- state assignments: {}", fp.states.iter().map(state_text).collect::<Vec<_>>().join("; "));
            let shaders = [("pixel shader", Some(&p.pixel), Some(p.pixel_bytes.len())), ("vertex shader", p.vertex.as_ref(), p.vertex_bytes.as_ref().map(|b| b.len()))];
            for (what, s, bytes) in shaders {
                let Some(s) = s else {
                    let _ = writeln!(out, "- {what}: none in the pass (the vertex shader of XNA's SpriteEffect stays bound: SpriteBatch's fixed vertex stage)");
                    continue;
                };
                let (floats, samplers) = constants_text(s);
                let _ = writeln!(out, "- {what}: `{}`, {} instructions, {} bytes", s.model(), s.executable().count(), bytes.unwrap_or(0));
                let _ = writeln!(out, "  - float constants (constant table): {floats}");
                if what == "pixel shader" {
                    let _ = writeln!(out, "  - samplers: {samplers} (sampler states in the effect: none; the device's `SamplerStates[n]` apply)");
                }
                let defs: Vec<String> = s.float_defs().map(|(r, v)| format!("`c{r}` = ({})", v.iter().map(|f| disasm::fmt_f32(*f)).collect::<Vec<_>>().join(", "))).collect();
                let _ = writeln!(out, "  - `def` constants: {}", if defs.is_empty() { "none".to_owned() } else { defs.join(", ") });
                match &s.preshader {
                    Some(pre) => {
                        let inputs: Vec<String> = pre.ctab.constants.iter().map(|c| format!("`{}` {} {}", c.registers(), c.hlsl(), c.name)).collect();
                        let outputs: Vec<String> = pre.outputs().iter().map(|(r, m)| format!("`c{r}.{}`", disasm::mask_text(*m))).collect();
                        let _ = writeln!(out, "  - preshader: {} instructions, {} literals; reads {}; writes {}", pre.instructions.len(), pre.literals.len(), inputs.join(", "), outputs.join(", "));
                    }
                    None => {
                        let _ = writeln!(out, "  - preshader: none");
                    }
                }
            }
            let _ = writeln!(out);
        }
    }
    out
}

fn main() {
    let Some(effects) = support::load_effects() else { std::process::exit(1) };
    let docs = support::docs_dir();
    // stale listings must not survive a regeneration
    for dir in ["asm", "wgsl"] {
        let _ = std::fs::remove_dir_all(docs.join(dir));
    }

    let mut total_ops: BTreeMap<&'static str, usize> = BTreeMap::new();
    let mut per_effect: Vec<BTreeMap<&'static str, usize>> = Vec::new();
    let mut pres_ops: BTreeMap<&'static str, usize> = BTreeMap::new();
    let mut translated: BTreeMap<String, Result<(), String>> = BTreeMap::new();
    let mut duplicates = Vec::new();
    for e in &effects {
        let mut ops = BTreeMap::new();
        for p in &e.passes {
            for s in [Some(&p.pixel), p.vertex.as_ref()].into_iter().flatten() {
                count_ops(s, &mut ops);
                count_ops(s, &mut total_ops);
                if let Some(pre) = &s.preshader {
                    for i in &pre.instructions {
                        *pres_ops.entry(i.op.name()).or_default() += 1;
                    }
                }
            }
            // assembly
            let mut asm = format!("// {}\n//\n", p.label());
            if let Some(vs) = &p.vertex {
                asm.push_str("// ---- vertex shader\n");
                asm.push_str(&disasm::listing(vs));
                asm.push_str("\n// ---- pixel shader\n");
            } else {
                asm.push_str("// No vertex shader in the pass (SpriteBatch's vertex stage).\n//\n");
            }
            asm.push_str(&disasm::listing(&p.pixel));
            write(&docs.join("asm").join(format!("{}.asm", p.stem())), &asm);
            // WGSL
            let result = wgsl::translate(&p.label(), &p.pixel, p.vertex.as_ref());
            if let Ok(t) = &result {
                write(&docs.join("wgsl").join(format!("{}.wgsl", p.stem())), &t.source);
            }
            translated.insert(p.stem(), result.map(|_| ()));
            if let Some(first) = e.passes.iter().find(|q| q.name == p.name && q.technique == p.technique && q.index < p.index) {
                duplicates.push(format!("`{}` pass {} `{}` repeats the name of pass {} ({}); XNA's `Passes[\"{}\"]` finds pass {}", e.name, p.index, p.name, first.index, if first.pixel_bytes == p.pixel_bytes { "identical bytecode" } else { "DIFFERENT bytecode" }, p.name, first.index));
            }
        }
        per_effect.push(ops);
        write(&docs.join(format!("{}.md", e.name)), &effect_listing(e));
    }

    // ---- COVERAGE.md
    let verification = std::fs::read_to_string(docs.join("verification.tsv")).unwrap_or_default();
    let rows: BTreeMap<(String, usize), Vec<String>> = verification
        .lines()
        .skip(1)
        .filter_map(|l| {
            let f: Vec<String> = l.split('\t').map(str::to_owned).collect();
            Some(((f.first()?.clone(), f.get(1)?.parse().ok()?), f))
        })
        .collect();
    let mut out = String::from("# Effect coverage\n\nGenerated by `cargo run -p terraria-shaders --example effects_docs`. Do not edit.\n\n");
    let _ = writeln!(out, "## Opcode histogram (vertex and pixel shaders of all passes)\n");
    let _ = writeln!(out, "| instruction | {} | total | translated and interpreted |", effects.iter().map(|e| e.name).collect::<Vec<_>>().join(" | "));
    let _ = writeln!(out, "|---|{}---|---|", "---|".repeat(effects.len()));
    let implemented = |name: &str| check::SUPPORTED.iter().any(|o| o.name() == name) || matches!(name, "texldp" | "texldb");
    for (name, n) in &total_ops {
        let cells: Vec<String> = per_effect.iter().map(|m| m.get(name).copied().unwrap_or(0).to_string()).collect();
        let how = match *name {
            "dcl" | "def" => "yes (declaration)",
            n if implemented(n) => "yes",
            _ => "NO",
        };
        let _ = writeln!(out, "| `{name}` | {} | {n} | {how} |", cells.join(" | "));
    }
    let unused: Vec<&str> = check::SUPPORTED.iter().map(|o| o.name()).filter(|n| !total_ops.contains_key(n)).collect();
    let _ = writeln!(out, "\nImplemented but not used by these files: {} (plus `texld` with the projected / bias flags and the `abs` source modifier).", unused.iter().map(|n| format!("`{n}`")).collect::<Vec<_>>().join(", "));
    let refused: Vec<&str> = Opcode::ALL.iter().filter(|o| !check::SUPPORTED.contains(o)).map(|o| o.name()).collect();
    let mut refused: Vec<&str> = refused;
    refused.dedup();
    let _ = writeln!(out, "\nDecoded and disassembled but refused by the translator and the interpreter with an error naming the instruction: {}.\n", refused.iter().map(|n| format!("`{n}`")).collect::<Vec<_>>().join(", "));
    let _ = writeln!(out, "## Preshader operations\n\n| operation | count |\n|---|---|");
    for (name, n) in &pres_ops {
        let _ = writeln!(out, "| `{name}` | {n} |");
    }
    let _ = writeln!(out, "\n## Duplicate pass names\n");
    if duplicates.is_empty() {
        let _ = writeln!(out, "None.");
    }
    for d in &duplicates {
        let _ = writeln!(out, "- {d}");
    }

    let _ = writeln!(out, "\n## Passes\n");
    let _ = writeln!(out, "Columns: `ps` / `pre` / `vs` = instruction counts of the pixel shader, its preshader and the vertex shader; `WGSL` = translated (the test `translate` also runs every module through naga's validator);");
    let _ = writeln!(out, "`linear` / `point` = largest error of the GPU against the interpreter in 8-bit steps over the pixels that are not on an edge, in the bilinear and the point-sampled run; `edges` = pixels above one step that sit on a discontinuity of the shader (see README.md); `colours` = distinct colours of the test image.\n");
    let (mut n_translated, mut n_verified) = (0, 0);
    for e in &effects {
        let _ = writeln!(out, "### {} ({} passes)\n", e.name, e.passes.len());
        let _ = writeln!(out, "| # | pass | class | ps | pre | vs | WGSL | linear | point | edges (linear / point) | colours | verified on the GPU |");
        let _ = writeln!(out, "|---|---|---|---|---|---|---|---|---|---|---|---|");
        for p in &e.passes {
            let ok = translated[&p.stem()].is_ok();
            n_translated += ok as usize;
            let row = rows.get(&(e.name.to_owned(), p.index));
            let cell = |k: usize| row.and_then(|r| r.get(k)).cloned().unwrap_or_else(|| "?".into());
            let verdict = cell(10);
            n_verified += (verdict.starts_with("match")) as usize;
            let edges = if cell(5) == "0" && cell(7) == "0" { "0".to_owned() } else { format!("{} / {}", cell(5), cell(7)) };
            let _ = writeln!(
                out,
                "| {} | [`{}`]({}.md#{}-{}) | {} | {} | {} | {} | {} | {} | {} | {edges} | {} | {} |",
                p.index,
                p.name,
                e.name,
                p.index,
                p.name.to_lowercase(),
                if check::is_inexact(&p.pixel) { "transcendental" } else { "arithmetic" },
                p.pixel.executable().count(),
                p.pixel.preshader.as_ref().map_or("-".to_owned(), |x| x.instructions.len().to_string()),
                p.vertex.as_ref().map_or("-".to_owned(), |v| v.executable().count().to_string()),
                match &translated[&p.stem()] {
                    Ok(()) => "yes".to_owned(),
                    Err(err) => format!("NO: {err}"),
                },
                cell(4),
                cell(6),
                cell(9),
                if verdict.starts_with("match") { verdict.replacen("match", "yes", 1) } else { format!("NO: {verdict}") }
            );
        }
        let _ = writeln!(out);
    }
    let total: usize = effects.iter().map(|e| e.passes.len()).sum();
    let _ = writeln!(out, "Totals: {total} passes, {n_translated} translated, {n_verified} verified against the interpreter on the GPU.");
    write(&docs.join("COVERAGE.md"), &out);
    println!("{total} passes: {n_translated} translated, {n_verified} verified; wrote {}", docs.display());
}
